#!/usr/bin/env python3
"""codemap: a deterministic, dependency-free map of a repository's code.

Usage:
  codemap.py build [--root DIR] [--redetect]   write the map (where: see below)
  codemap.py check [--root DIR] [--out PATH]   exit 0 if the map is current, 1 if stale
                                               (warnings: broken vault links, dead sources)
  codemap.py query TERM [--root DIR]           where TERM is defined, which paths match it,
                                               who imports them, which vault pages mention them
  codemap.py mentions [PATH...] [--base SHA]   vault pages that mention these files (or the
                                               files changed since SHA)
  codemap.py changed --base SHA --head SHA     pointers for a review of `git diff SHA...SHA`: the
                                               changed files, the top-level definitions whose text
                                               differs (`(module level)`: the text above them),
                                               who imports them, their tests and the vault pages
                                               that mention them (60 lines at most); then,
                                               only when found, possible weakened guards
  codemap.py query TERM --budget N             the same, ranked (exact matches, then the most
                                               imported or linked) and cut at about N tokens
  codemap.py impact [PATH...] [--base SHA]     who depends on these files (or the files changed
                    [--depth N]                since SHA): importers up to N levels (default 2),
                                               their tests, and the files naming their definitions
  codemap.py calls NAME... [--all]             where these Python functions are defined, who
                                               calls them (resolved), other possible uses, a
                                               text count and what it cannot see (live, `ast`)
  codemap.py detect [--root DIR]               where the vault and the map are, and why
  codemap.py check --quiet                     the same check: one line when stale, else none
  codemap.py install-hook | uninstall-hook     the opt-in git pre-commit hook for this clone
  codemap.py pre-commit                        what that hook runs (refresh and stage the map)
  codemap.py claude-hook                       the opt-in Claude Code hook (JSON on stdin)
  codemap.py rules-hint [--remove]             the marked block in AGENTS.md and CLAUDE.md
  codemap.py session-hook                      the SessionStart hook: one line when that block
                                               is older than this template (JSON on stdin)

The vault and map locations come from .codemap.json at the repository root. Without it they
are detected (a folder with .obsidian/, a known vault folder name, or the folder holding most
pages with [[wikilinks]]); the first build writes .codemap.json so later runs agree. An existing
hand-written map.md is never overwritten: the map then goes to code-map.md.

Only the Python standard library is used (Python 3.8+). Files come from `git ls-files`, so
ignored files and symlinks are skipped. Symbols are top-level definitions found with line
patterns for every language (approximate, and the same on every Python version). Nothing is
executed and nothing is sent anywhere. The vault link rules and the secret-file patterns follow
ideas from graphify (Apache-2.0); no code was copied.
"""
