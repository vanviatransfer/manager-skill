def git_lines(root, args, nul=True):
    out = subprocess.run(["git", "-C", root] + args, capture_output=True, check=True)
    text = out.stdout.decode("utf-8", "replace")
    return [x for x in text.split("\0" if nul else "\n") if x]


def readable_file(root, path):
    return not link_in_path(root, path) and os.path.isfile(os.path.join(root, *path.split("/")))


def arg_batches(paths, limit=24000):
    """The paths in runs whose total length stays under a command-line limit (Windows: 32,767)."""
    batch, size = [], 0
    for p in paths:
        if batch and size + len(p) + 3 > limit:
            yield batch
            batch, size = [], 0
        batch.append(p)
        size += len(p) + 3
    if batch:
        yield batch


def blob_bytes(root, ids):
    """The bytes of each blob, in the order asked, from one `git cat-file --batch`."""
    out = subprocess.run(["git", "-C", root, "cat-file", "--batch"], capture_output=True,
                         check=True, input="".join(blob + "\n" for blob in ids).encode())
    data, pos, found = out.stdout, 0, []
    for _ in ids:
        end = data.index(b"\n", pos)
        size = int(data[pos:end].split()[2])
        found.append(data[end + 1:end + 1 + size])
        pos = end + 2 + size
    return found


def file_hashes(root, paths, filters=False):
    """The blob id of each file's working-tree bytes, in the order asked: of the raw bytes, or
    with `filters` of what `git add` would store (its clean filter, `ident`, line-ending and
    `working-tree-encoding` conversions). git writes no object for either."""
    kind = [] if filters else ["--no-filters"]
    found = []
    for batch in arg_batches(paths):
        out = subprocess.run(["git", "-C", root, "hash-object"] + kind + ["--"] + batch,
                             capture_output=True, check=True)
        got = out.stdout.decode().split()
        if len(got) != len(batch):
            raise GitError("git hash-object returned %d hashes for %d files"
                           % (len(got), len(batch)))
        found += got
    return found


def worktree_differs(root, paths, blobs):
    """The paths whose working-tree bytes, as the scan would read them, aren't the indexed blob.

    Raw bytes (git hash-object --no-filters), so a clean filter, assume-unchanged or
    skip-worktree can't hide a change. Paths go to git as arguments after `--`, never as lines
    git would unquote. A file whose raw bytes differ is compared with its blob after the scan's
    own CRLF-to-LF step, so a core.autocrlf checkout isn't a change. Missing paths and those
    that aren't readable regular files are left to the caller (see readable_file)."""
    present = [p for p in paths if p in blobs and readable_file(root, p)]
    differs = [p for p, b in zip(present, file_hashes(root, present)) if b != blobs[p]]
    if not differs:
        return []
    changed = []
    for p, blob in zip(differs, blob_bytes(root, [blobs[p] for p in differs])):
        with open(os.path.join(root, *p.split("/")), "rb") as fh:
            if fh.read().replace(b"\r\n", b"\n") != blob.replace(b"\r\n", b"\n"):
                changed.append(p)
    return changed


# `changed`: pointers for a review of `git diff base...head`. Definitions are read from the two
# commits; importers, tests and vault mentions from the scan of the working tree.
TEST_AFFIX = re.compile(r"^test_|(?:_test|_spec|\.test|\.spec|Tests?)$")


def diff_entries(root, base, head):
    """[(status letter, path, base blob, head blob)] of `git diff base...head`: the paths under
    root, relative to it; a blob is None on a side where the path is no regular file."""
    items = git_lines(root, ["diff", "--raw", "-z", "--no-renames", "--relative", "--no-abbrev",
                             "%s...%s" % (base, head)])
    found = []
    for meta, path in zip(items[0::2], items[1::2]):
        old_mode, new_mode, old, new, status = meta[1:].split()
        found.append((status[0], path, old if old_mode.startswith("100") else None,
                      new if new_mode.startswith("100") else None))
    return found


def definitions(path, data):
    """{name: text} of the top-level definitions in a source file's bytes (None: none), to compare
    two versions of it. One runs from the comment and decorator lines right above it up to the
    next one's, so a change between two counts for the first; Python's private ones are included.
    Under MODULE_LEVEL: the text above the first one (all of it when there is none), without its
    empty lines.
    """
    if data is None or len(data) > MAX_BYTES or b"\0" in data[:8192]:
        return {}
    text = data.replace(b"\r\n", b"\n").decode("utf-8", "replace")
    ext = posixpath.splitext(path)[1].lower()
    key = PATTERN_KEY.get(ext)
    if ext in C_EXT:
        symbols = sorted(cpp_page(CppFile(path, text))[0], key=lambda x: (x[1], x[0]))
    else:
        symbols = pattern_info(text, key)[0] if key else python_info(text, private=True)[0]
    lines, starts = text.split("\n"), []
    for _, start in symbols:
        while start > 1 and lines[start - 2].lstrip()[:1] in ("@", "#", "/", "*"):
            start -= 1
        starts.append(start)
    starts.append(len(lines) + 1)
    found = {MODULE_LEVEL: "\n".join(line for line in lines[:starts[0] - 1] if line.strip())}
    for (name, _), start, end in zip(symbols, starts, starts[1:]):
        found[name] = found.get(name, "") + "\n".join(lines[start - 1:end - 1]).rstrip() + "\n"
    return found


def changed_lines(root, diff, head, info, importers, mentions, out_rel):
    """The lines `changed` prints, before the cap: per file of `diff`, the `diff_entries` of
    `git diff base...head` (map pages left out), its status and path, then what there is of: the
    top-level definitions whose text differs between the two commits (first MODULE_LEVEL, when
    the text above them differs), the files that import it (a deleted file: `scan` was given
    its path), its tests (they import it, or a source file gives them its name) and the vault
    lines that mention it. Files that may hold secrets are never read."""
    def parsed(path):
        ext = posixpath.splitext(path)[1].lower()
        return (ext == ".py" or ext in PATTERN_KEY or ext in C_EXT) and not skipped(path, out_rel)

    entries = [e for e in diff if not is_map_page(e[1], out_rel)]
    blobs = sorted({blob for _, path, old, new in entries if parsed(path)
                    for blob in (old, new) if blob})
    data = dict(zip(blobs, blob_bytes(root, blobs)))
    tests = {}
    for path in sorted(info):
        if is_test(path):
            stem = posixpath.splitext(posixpath.basename(path))[0]
            tests.setdefault(TEST_AFFIX.sub("", stem).lower(), []).append(path)
    lines = ["changed: %d file%s" % (len(entries), "" if len(entries) == 1 else "s")]
    if len(set(git_lines(root, ["rev-parse", "HEAD", head + "^{commit}"], nul=False))) > 1:
        lines.append("note: HEAD is not %s; importers, tests and vault pages are the working "
                     "tree's" % head)
    for status, path, old, new in entries:
        lines.append("%s %s" % (status, path))
        before = definitions(path, data.get(old) if parsed(path) else None)
        after = definitions(path, data.get(new) if parsed(path) else None)
        above = (before.pop(MODULE_LEVEL, None), after.pop(MODULE_LEVEL, None))
        new_mark, gone_mark = (" (new)", " (removed)") if status == "M" else ("", "")
        names = [MODULE_LEVEL] if None not in above and above[0] != above[1] else []
        names += [name + ("" if name in before else new_mark) for name in after
                  if after[name] != before.get(name)]
        names += [name + gone_mark for name in before if name not in after]
        users = importers.get(path, [])
        stem, ext = posixpath.splitext(posixpath.basename(path).lower())
        named = tests.get(stem, []) if ext in LANG and not is_test(path) else []
        for label, items in (
                ("definitions", names),
                ("imported by", [user for user in users if not is_test(user)]),
                ("tests", sorted(set(named) | {user for user in users if is_test(user)})),
                ("vault", ["%s:%d" % where for where in mentions_of(mentions, path)])):
            if items:
                more = len(items) - (MAX_CHANGED_NAMES if label == "definitions" else MAX_SYMBOLS)
                lines.append("  %s: %s%s" % (label, ", ".join(items[:len(items) - max(more, 0)]),
                                             " (+%d more)" % more if more > 0 else ""))
    return lines


# `changed`: possible weakened guards, a section printed only when something is found. By path,
# and by counting marker lines in the two versions of each file (so a moved line counts for
# nothing): approximate, never a filter.
MAX_GUARD_LINES = 8
PROSE = (".md", ".markdown", ".rst", ".txt", ".adoc")  # docs naming a marker are no finding
SKIP_MARKS = (  # (label, pattern, in test files only, a call); a line counts for its first match
    ("@unittest.skip", re.compile(r"@unittest\.skip(?![A-Za-z])"), False, False),
    ("skipTest(", re.compile(r"\.skipTest\("), False, True),
    ("pytest.mark.skip", re.compile(r"\bpytest\.mark\.skip(?![A-Za-z])"), False, False),
    ("pytest.mark.xfail", re.compile(r"\bpytest\.mark\.xfail"), False, False),
    ("@Disabled", re.compile(r"@Disabled\b"), False, False),
    ("t.Skip(", re.compile(r"\bt\.Skip(?:Now|f)?\("), False, True),
    (".only(", re.compile(r"\.only\("), True, False),
    ("xit(", re.compile(r"\bxit\("), True, False),
    ("xdescribe(", re.compile(r"\bxdescribe\("), True, False),
    (".skip(", re.compile(r"\.skip\("), True, True),
)
# A skip call is conditional (not counted) after an `if` on its line, or inside a block that one
# of these opens: the nearest line above it with less indentation.
CONDITION = re.compile(r"^\s*(?:\}\s*)?(?:if|elif|else|except|catch|case|when|unless)\b")
IF_BEFORE = re.compile(r"\bif\b")
# A `noqa` whose only code is E402 (an import after a sys.path setup): matched at the line's
# first `# noqa`, with no further code (letters then digits) after E402, whatever separates them.
NOQA_IMPORT = re.compile(r"#\s*noqa:\s*E402\b(?![^\n]*[A-Za-z]+\d)", re.I)
SUPPRESSIONS = (
    ("noqa", re.compile(r"#\s*noqa\b", re.I)),
    ("type: ignore", re.compile(r"#\s*type:\s*ignore\b")),
    ("eslint-disable", re.compile(r"\beslint-disable")),
    ("@ts-ignore", re.compile(r"@ts-(?:ignore|nocheck)\b")),
    ("nolint", re.compile(r"//\s*nolint\b")),
    ("pragma: no cover", re.compile(r"#\s*pragma:\s*no\s*cover\b")),
)
ASSERT_LINE = re.compile(r"assert|\bexpect\b", re.I)
TOML_HEADER = re.compile(r"^\s*\[\[?\s*([^\]]+?)\s*\]\]?\s*(?:#.*)?$")


def check_config(path):
    """The kind of lint, format, type-check, test or CI configuration a path is, or None."""
    name = posixpath.basename(path).lower()
    if path.startswith((".github/workflows/", ".circleci/")) or name in (
            ".gitlab-ci.yml", ".travis.yml", "azure-pipelines.yml", "jenkinsfile"):
        return "CI"
    if name.startswith(".pre-commit-config"):
        return "pre-commit"
    if name in (".flake8", "ruff.toml", ".ruff.toml", ".pylintrc", "pylintrc") or \
            name.startswith((".eslintrc", "eslint.config.", ".golangci", ".stylelintrc")):
        return "lint"
    if name in ("mypy.ini", ".mypy.ini", "pyrightconfig.json") or \
            (name.startswith("tsconfig") and name.endswith(".json")):
        return "type-check"
    if name.startswith((".prettierrc", "prettier.config.")):
        return "format"
    if name in ("setup.cfg", "tox.ini", "pytest.ini", ".coveragerc"):
        return "lint/test"
    return None


def tool_sections(text):
    """{name: text} of a pyproject.toml's [tool.*] tables."""
    found, name = {}, None
    for line in text.split("\n"):
        m = TOML_HEADER.match(line)
        if m:
            name = m.group(1) if m.group(1).startswith("tool.") else None
        if name:
            found[name] = found.get(name, "") + line + "\n"
    return found


def conditional(lines, n, start):
    """Whether the skip call at column `start` of lines[n] runs only under a condition: an `if`
    before it on its line, or the nearest line above with less indentation opens a branch."""
    line = lines[n]
    if IF_BEFORE.search(line[:start]):
        return True
    indent = len(line) - len(line.lstrip())
    for above in reversed(lines[:n]):
        if above.strip() and len(above) - len(above.lstrip()) < indent:
            return bool(CONDITION.match(above))
    return False


def guard_marks(text, test):
    """({skip label: lines}, {suppression label: lines}, assert/expect lines) of a file's text;
    skip markers marked test-only and assert lines are counted in test files only. Conditional
    skips (`skipIf`, `skipUnless`, `pytest.mark.skipif`, a skip call under a condition) and a
    `noqa` for E402 are not counted."""
    skips, quiet, asserts = {}, {}, 0
    lines = text.split("\n")
    for n, line in enumerate(lines):
        for label, rx, test_only, call in SKIP_MARKS:
            m = rx.search(line) if test or not test_only else None
            if m:
                if not (call and conditional(lines, n, m.start())):
                    skips[label] = skips.get(label, 0) + 1
                break
        for label, rx in SUPPRESSIONS:
            found = rx.search(line)
            if found:
                if not (label == "noqa" and NOQA_IMPORT.match(line, found.start())):
                    quiet[label] = quiet.get(label, 0) + 1
                break
        if test and ASSERT_LINE.search(line):
            asserts += 1
    return skips, quiet, asserts


def renamed_paths(root, base, head):
    """[(old path, new path)] of the renames git detects in `git diff base...head`."""
    items = git_lines(root, ["diff", "--name-status", "-z", "-M", "--relative",
                             "%s...%s" % (base, head)])
    found, n = [], 0
    while n < len(items):
        status = items[n]
        if status[:1] in ("R", "C"):
            if status[0] == "R":
                found.append((items[n + 1], items[n + 2]))
            n += 3
        else:
            n += 2
    return found


def weakened_lines(root, base, head, diff, out_rel):
    """The `possible weakened guards` section of `changed`, [] when nothing is found: test files
    deleted, renamed or moved; skip markers and suppressions added; net-removed assert/expect
    lines in a test file; edited lint, format, type-check, test or CI configuration. At most
    MAX_GUARD_LINES findings, then a count of the rest (all of them when one more would fit).
    Files that may hold secrets are never read."""
    entries = [e for e in diff if not is_map_page(e[1], out_rel)]
    moves = [(o, n) for o, n in renamed_paths(root, base, head)
             if not is_map_page(o, out_rel) and not is_map_page(n, out_rel)]
    gone, came = {o: n for o, n in moves}, {n: o for o, n in moves}
    old_blob = {path: old for _, path, old, _ in entries}
    found = []
    for o, n in moves:
        if is_test(o):
            where = ("moved and renamed" if posixpath.dirname(o) != posixpath.dirname(n) and
                     posixpath.basename(o) != posixpath.basename(n) else
                     "moved" if posixpath.dirname(o) != posixpath.dirname(n) else "renamed")
            found.append((0, o, "test file", "%s to %s%s" % (
                where, n, "" if is_test(n) else ", no longer named as a test")))
    sides = []  # (path, base blob, head blob, test file)
    for status, path, old, new in entries:
        kind = check_config(path)
        if kind:
            found.append((3, path, "check config", "%s config %s" % (
                kind, {"A": "added", "D": "deleted"}.get(status, "edited"))))
        if path in gone:
            continue
        if status == "D" and is_test(path):
            found.append((0, path, "test file", "deleted"))
            continue
        before = old_blob.get(came[path]) if path in came else old
        # test code: a test file in a language the map parses (no data files or fixtures)
        test = (is_test(path) or (path in came and is_test(came[path]))) and \
            posixpath.splitext(path)[1].lower() in LANG
        if not path.lower().endswith(PROSE) and not skipped(path, out_rel):
            sides.append((path, before, new, test))
    blobs = sorted({b for _, old, new, _ in sides for b in (old, new) if b})
    data = dict(zip(blobs, blob_bytes(root, blobs)))

    def text(blob):
        raw = data.get(blob) if blob else None
        if raw is None or len(raw) > MAX_BYTES or b"\0" in raw[:8192]:
            return ""
        return raw.replace(b"\r\n", b"\n").decode("utf-8", "replace")

    for path, old, new, test in sides:
        before, after = text(old), text(new)
        if posixpath.basename(path).lower() == "pyproject.toml":
            was, now = tool_sections(before), tool_sections(after)
            names = sorted(k for k in set(was) | set(now) if was.get(k) != now.get(k))
            if names:
                found.append((3, path, "check config", "%s edited" % ", ".join(
                    "[%s]" % k for k in names[:3]) + (" (+%d more)" % (len(names) - 3)
                                                      if len(names) > 3 else "")))
        (skips0, quiet0, asserts0), (skips1, quiet1, asserts1) = \
            guard_marks(before, test), guard_marks(after, test)
        for order, kind, was, now in ((1, "skip marker", skips0, skips1),
                                      (4, "suppression", quiet0, quiet1)):
            added = ["+%d %s" % (now[k] - was.get(k, 0), k) for k in sorted(now)
                     if now[k] > was.get(k, 0)]
            if added:
                found.append((order, path, kind, ", ".join(added)))
        if test and asserts0 > asserts1:
            found.append((2, path, "asserts", "%d fewer assert/expect line%s" % (
                asserts0 - asserts1, "" if asserts0 - asserts1 == 1 else "s")))
    if not found:
        return []
    found.sort()
    lines = ["possible weakened guards (approximate, never a filter):"]
    shown = found if len(found) <= MAX_GUARD_LINES + 1 else found[:MAX_GUARD_LINES]
    lines += ["  %s: %s: %s" % (kind, path, why) for _, path, kind, why in shown]
    if len(shown) < len(found):  # as the 60-line cap: a more-line only for two or more
        lines.append("  … %d more" % (len(found) - len(shown)))
    return lines


# `impact` and `query --budget`: run only when asked; nothing calls them by default.
WORD = re.compile(r"[A-Za-z_$][\w$]*")


def lang_family(lang):
    """Languages whose files can use each other's names: JavaScript and TypeScript, C and C++."""
    return {"TypeScript": "JavaScript", "C++": "C", "C/C++": "C"}.get(lang, lang)


def impact_word(name, lang):
    """The word a definition's name is found by: C/C++ `AMyActor::Fire` by `Fire`."""
    if lang in C_LANGS:
        return name.split("::")[-1].lstrip("~")
    return name.rstrip("?!")


def short_list(items, limit=IMPACT_NAMES):
    more = len(items) - limit
    return ", ".join(items[:limit]) + (" (+%d more)" % more if more > 0 else "")


def impact_lines(root, targets, depth, info, importers, out_rel):
    """The lines `impact` prints: per target file the map knows, its importers (import-based,
    each file once: direct, then each further level up to `depth`), the tests among them and
    those of its language family named after it (`test_<name>` ...), and per top-level
    definition the other source files of its language family whose text (Python: outside
    strings and comments) holds its name as a whole word, importers first (name-based: anything
    else of the same name counts too). Targets the map doesn't parse are named on one line at the
    end. `main` cuts it at MAX_CHANGED_LINES."""
    paths = sorted(set(targets))
    known = [p for p in paths if p in info]
    tests_by_stem = {}
    for p in sorted(info):
        stem = posixpath.splitext(posixpath.basename(p))[0]
        if is_test(p) and TEST_AFFIX.sub("", stem) != stem:  # a test_ / _test ... affix, not
            tests_by_stem.setdefault(TEST_AFFIX.sub("", stem).lower(), []).append(p)  # __init__
    wanted = {impact_word(n, info[p]["lang"]) for p in known
              for n, _ in info[p]["symbols"][:MAX_CHANGED_NAMES]}
    users_of = {}
    for p in sorted(info) if wanted else ():
        text = read_text(root, p) or ""
        if info[p]["lang"] == "Python":  # outside strings and comments
            state, code = None, []
            for line in text.split("\n"):
                part, state = code_part(line, state)
                code.append(part)
            text = "\n".join(code)
        for word in wanted.intersection(WORD.findall(text)):
            users_of.setdefault(word, []).append(p)
    possible = possible_importers(info)
    lines = ["impact: %d source file%s (imported by, depth, tests: import-based; tests by name, "
             "referenced: name-based, may include false matches)"
             % (len(known), "" if len(known) == 1 else "s")]
    for path in known:
        lines.append(path)
        found, seen = set(), {path}
        if info[path]["lang"] not in IMPORT_LANGS:
            lines.append("  imports: not parsed for %s" % info[path]["lang"])
        else:
            level = [path]
            for n in range(1, depth + 1):
                level = sorted({u for p in level for u in importers.get(p, ())} - seen)
                if not level:
                    break
                seen.update(level)
                found.update(u for u in level if is_test(u))
                rest = [u for u in level if not is_test(u)]
                if rest:
                    lines.append("  %s: %s" % ("imported by" if n == 1 else "depth %d" % n,
                                               short_list(rest)))
            if found:
                lines.append("  tests: %s" % short_list(sorted(found)))
            maybe = [u for u in possible.get(path, ()) if u not in seen]
            if maybe:  # found through include paths this tool doesn't read: not followed
                lines.append("  not followed: possibly imported by %s (an `#include` path found "
                             "under no include folder read, ending only this file's path)"
                             % short_list(maybe))
        names, family = [n for n, _ in info[path]["symbols"]], lang_family(info[path]["lang"])
        stem = posixpath.splitext(posixpath.basename(path).lower())[0]
        named = [t for t in tests_by_stem.get(stem, []) if t not in found and t != path
                 and lang_family(info[t]["lang"]) == family]
        if named and not is_test(path):
            lines.append("  tests by name: %s" % short_list(named))
        for name in names[:MAX_CHANGED_NAMES]:
            users = [u for u in users_of.get(impact_word(name, info[path]["lang"]), [])
                     if u != path and lang_family(info[u]["lang"]) == family]
            users.sort(key=lambda u: u not in seen)  # importers first, each part sorted
            if users:
                lines.append("  referenced: %s: %s" % (name, short_list(users, MAX_SYMBOLS)))
        if len(names) > MAX_CHANGED_NAMES:
            lines.append("  (+%d more definitions)" % (len(names) - MAX_CHANGED_NAMES))
    other = [p for p in paths if p not in info and not is_map_page(p, out_rel)]
    if other:
        lines.append("not a source file in the map (other type, skipped or deleted): %s"
                     % short_list(other))
    return lines


MAYBE_LINE = "    possibly imported by %s (not followed: an unresolved `#include` ends this path)"


def possible_importers(info):
    """{tracked file: the C/C++ files with an unresolved `#include` whose path ends only that
    file's path} (whole folder names; `gtest/gtest.h` ends `test/gtest/gtest/gtest.h`)."""
    found = {}
    for p in sorted(info):
        for _, _, near in info[p].get("near", ()):
            if len(near) == 1 and near[0] != p and p not in found.get(near[0], ()):
                found.setdefault(near[0], []).append(p)
    return found


def not_followed(data):
    """`; <k> of its includes not followed` for a C/C++ file, else nothing."""
    k = len(data.get("unresolved", ())) + data.get("computed", 0)
    return "; %d of its includes not followed" % k if k else ""


def query_ranked(term, budget, info, importers, mentions, vault):
    """The lines of `query --budget`: the same items as `query` (50 per section at most),
    ranked (exact name or path matches first, then by how many files import the file or link to
    the page, then in `query`'s order) and kept, in rank order, while the output stays within
    about `budget` tokens (characters / CHARS_PER_TOKEN): one that doesn't fit is skipped, a
    later smaller one may still go in. The first ranked item is always kept; a cut ends with one
    line."""
    items = []  # (rank, section, lines)
    possible = possible_importers(info)
    for p, d in sorted(info.items()):
        for n, ln in d["symbols"]:
            if term in n.lower():
                rank = (n.lower() != term, -len(importers.get(p, ())), 0, len(items))
                note = d.get("notes", {}).get((n, ln), "")
                items.append((rank, 0, ["  %s:%d %s%s" % (p, ln, n, note)]))
    for p in sorted(info):
        if term in p.lower():
            users = importers.get(p, [])
            if info[p]["lang"] in IMPORT_LANGS:
                block = ["  %s (imported by %d local files%s)" % (p, len(users),
                                                                   not_followed(info[p]))]
            else:
                block = ["  %s (imports not parsed for %s)" % (p, info[p]["lang"])]
            block += ["    <- %s" % u for u in users[:20]]
            block += [MAYBE_LINE % u for u in possible.get(p, ())[:20]]
            block += ["    mentioned in %s:%d" % m for m in mentions_of(mentions, p)[:20]]
            low = p.lower()
            exact = term in (low, posixpath.basename(low), posixpath.splitext(low)[0]) or \
                low.endswith("/" + term) or posixpath.splitext(low)[0].endswith("/" + term)
            items.append(((not exact, -len(users), 1, len(items)), 1, block))
    for pg in vault["pages"] if vault else ():
        title = vault["meta"][pg][0]
        low = pg.lower()
        if term in low or term in title.lower():
            exact = term in (low, title.lower(), posixpath.splitext(posixpath.basename(low))[0])
            block = ["  %s — %s (%d words, linked from %d)" % (pg, title, vault["meta"][pg][1],
                                                              vault["inbound"][pg])]
            items.append(((not exact, -vault["inbound"][pg], 2, len(items)), 2, block))
    heads = ["defined:", "paths:", "vault pages:"][:3 if vault else 2]
    present = {s for _, s, _ in items}
    shown, capped = {}, []  # `query` shows 50 items per section; the budget only cuts further
    for item in items:  # still in `query`'s order
        shown[item[1]] = shown.get(item[1], 0) + 1
        if shown[item[1]] <= 50:
            capped.append(item)
    over, items = len(items) - len(capped), capped
    size = sum(len(h) + 7 for s, h in enumerate(heads) if s not in present)  # "<head> none\n"
    ordered, total = sorted(items), len(items) + over
    full = size + sum(len(line) + 1 for _, _, block in ordered for line in block) + \
        sum(len(heads[s]) + 1 for s in present)
    limit = budget * CHARS_PER_TOKEN
    if full > limit or over:  # room for the line that says how many were cut
        limit -= len("… %d more (raise --budget)\n" % total)
    kept, count = {}, 0
    for _, s, block in ordered:  # in rank order; one that doesn't fit leaves room for the next
        cost = sum(len(line) + 1 for line in block) + (0 if s in kept else len(heads[s]) + 1)
        if kept and size + cost > limit:
            continue
        size += cost
        count += 1
        kept.setdefault(s, []).extend(block)
    lines = []
    for s, h in enumerate(heads):
        if s not in present:
            lines.append(h + " none")
        elif s in kept:
            lines += [h] + kept[s]
    if count < total:
        lines.append("… %d more (raise --budget)" % (total - count))
    return lines


