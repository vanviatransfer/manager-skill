class GitError(Exception):
    pass


def in_git_repo(root):
    d = root
    while True:
        if os.path.exists(os.path.join(d, ".git")):
            return True
        parent = os.path.dirname(d)
        if parent == d:
            return False
        d = parent


def git_files(root):
    try:
        out = subprocess.run(["git", "-C", root, "ls-files", "-s", "-z"], capture_output=True,
                             check=True)
        files = []
        for entry in out.stdout.decode("utf-8", "replace").split("\0"):
            meta, _, path = entry.partition("\t")
            if path and not meta.startswith("120000"):  # symlinks are skipped on every OS
                files.append(path)
    except (OSError, subprocess.CalledProcessError) as exc:
        if in_git_repo(root):
            detail = getattr(exc, "stderr", b"") or b""
            raise GitError("git ls-files failed: %s" % (detail.decode("utf-8", "replace").strip()
                                                          or exc))
        files = []
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for name in filenames:
                rel = os.path.relpath(os.path.join(dirpath, name), root)
                files.append(rel.replace(os.sep, "/"))
    return sorted(set(files))


def skipped(path, out_rel):
    if path == out_rel or SENSITIVE.search(path):
        return True
    parts = path.split("/")
    if any(p in SKIP_DIRS for p in parts[:-1]):
        return True
    return path.endswith(SKIP_SUFFIXES)


def read_text(root, path):
    full = os.path.join(root, *path.split("/"))
    try:
        if os.path.islink(full) or os.path.getsize(full) > 2 * MAX_BYTES:
            return None
        with open(full, "rb") as fh:
            data = fh.read().replace(b"\r\n", b"\n")
    except OSError:
        return None
    if len(data) > MAX_BYTES or b"\0" in data[:8192]:
        return None
    return data.decode("utf-8", "replace")


PY_DEF = re.compile(r"^(?:async\s+)?(?:def|class)\s+([A-Za-z]\w*)")
PY_IMPORT = re.compile(r"^import\s+(.+)")
PY_FROM = re.compile(r"^from\s+(\.*)([\w.]*)\s+import\s+(.+)")


def code_part(line, state):
    """(code of the line outside strings and comments, string state after the line).

    state is None or the open triple quote. Single-line strings and comments are blanked.
    """
    out, i, n = [], 0, len(line)
    while i < n:
        if state:
            end = line.find(state, i)
            while end > 0 and (len(line[:end]) - len(line[:end].rstrip("\\"))) % 2 == 1:
                end = line.find(state, end + 1)
            if end < 0:
                return "".join(out), state
            i, state = end + 3, None
            out.append(" ")
            continue
        c = line[i]
        if c == "#":
            break
        if line.startswith('"""', i) or line.startswith("'''", i):
            state = line[i:i + 3]
            i += 3
            continue
        if c in "'\"":
            j = i + 1
            while j < n and line[j] != c:
                j += 2 if line[j] == "\\" else 1
            out.append('""')
            i = j + 1
            continue
        out.append(c)
        i += 1
    return "".join(out), state


def python_info(text):
    """Top-level defs and imports from column-0 code, outside strings and comments.

    Line patterns, not `ast`, so the result doesn't depend on the Python version running it.
    """
    symbols, imports = [], []
    lines = text.split("\n")
    state = None
    n = 0
    while n < len(lines):
        raw = lines[n]
        n += 1
        starts_in_string = state is not None
        code, state = code_part(raw, state)
        if starts_in_string or not code.strip() or raw[0].isspace():
            continue
        m = PY_DEF.match(code)
        if m:
            if not m.group(1).startswith("_"):
                symbols.append((m.group(1), n))
            continue
        while code.rstrip().endswith("\\") and n < len(lines):
            more, state = code_part(lines[n], state)
            code, n = code.rstrip()[:-1] + " " + more, n + 1
        m = PY_FROM.match(code) or PY_IMPORT.match(code)
        if not m:
            continue
        names = m.group(m.lastindex)
        if names.strip().startswith("(") and ")" not in names:
            while n < len(lines) and ")" not in names:
                more, state = code_part(lines[n], state)
                names, n = names + " " + more, n + 1
        names = [x.split(" as ")[0].strip(" ()\\") for x in names.split(",")]
        names = [x for x in names if x and x != "*"]
        if m.re is PY_IMPORT:
            imports.extend((0, x) for x in names)
        else:
            level, module = len(m.group(1)), m.group(2)
            imports.append((level, module))
            imports.extend((level, (module + "." + x).strip(".")) for x in names)
    return symbols, imports


def pattern_info(text, key):
    symbols, imports = [], []
    for lineno, line in enumerate(text.split("\n"), 1):
        for pat in PATTERNS[key]:
            m = pat.match(line)
            if m:
                symbols.append((m.group(1), lineno))
                break
        if key == "js":
            imports.extend((0, m.group(1)) for m in JS_IMPORT.finditer(line))
    return symbols, imports


def resolve_python(path, level, module, known):
    if level:
        base = posixpath.dirname(path)
        for _ in range(level - 1):
            base = posixpath.dirname(base)
        parts = [p for p in [base] + module.split(".") if p]
    else:
        parts = module.split(".")
    stem = "/".join(parts)
    cands = [stem + ".py", stem + "/__init__.py"]
    if not level:
        here = posixpath.dirname(path)
        cands = [posixpath.join(here, c) for c in cands] + cands + ["src/" + c for c in cands]
    for c in cands:
        c = posixpath.normpath(c)
        if c in known:
            return c
    return None


def resolve_js(path, spec, known):
    base = posixpath.normpath(posixpath.join(posixpath.dirname(path), spec))
    if base in known:
        return base
    stem = base
    for ext in (".js", ".jsx", ".mjs", ".cjs"):
        if stem.endswith(ext):
            stem = stem[: -len(ext)]
    for ext in JS_EXT:
        for c in (stem + ext, stem + "/index" + ext):
            if c in known:
                return c
    return None


def package_entries(root, known):
    entries = set()
    text = read_text(root, "package.json") if "package.json" in known else None
    if text:
        try:
            pkg = json.loads(text)
        except ValueError:
            pkg = {}
        if not isinstance(pkg, dict):
            pkg = {}
        vals = [pkg.get("main")]
        b = pkg.get("bin")
        vals += list(b.values()) if isinstance(b, dict) else [b]
        for v in vals:
            if isinstance(v, str):
                p = posixpath.normpath(v.lstrip("./") if v.startswith("./") else v)
                if p in known:
                    entries.add(p)
    return entries


def scan(root, out_rel, tracked):
    files = [f for f in tracked if not skipped(f, out_rel)]
    known = set(files)
    info = {}
    for path in files:
        ext = posixpath.splitext(path)[1].lower()
        if ext not in LANG:
            continue
        text = read_text(root, path)
        if text is None:
            continue
        if ext == ".py":
            symbols, raw = python_info(text)
            deps = {resolve_python(path, lvl, mod, known) for lvl, mod in raw}
        elif ext in PATTERN_KEY:
            symbols, raw = pattern_info(text, PATTERN_KEY[ext])
            deps = {resolve_js(path, spec, known) for _, spec in raw} if ext in JS_EXT else set()
        else:
            symbols, deps = [], set()
        deps.discard(None)
        deps.discard(path)
        deps -= {d for d in deps if d.endswith("/__init__.py")
                 and any(x != d and x.startswith(d[: -len("__init__.py")]) for x in deps)}
        info[path] = {"lang": LANG[ext], "symbols": symbols, "deps": sorted(deps)}
    importers = {}
    for path, data in info.items():
        for d in data["deps"]:
            importers.setdefault(d, []).append(path)
    for v in importers.values():
        v.sort()
    entries = package_entries(root, known)
    for path in info:
        stem = posixpath.splitext(posixpath.basename(path))[0].lower()
        if stem in ENTRY_NAMES and path.count("/") <= 2:
            entries.add(path)
    return info, importers, sorted(e for e in entries if e in info), files


def is_test(path):
    parts = path.split("/")
    return any(p.lower() in TEST_DIRS for p in parts[:-1]) or bool(TEST_FILE.search(parts[-1]))


def top_dir(path):
    return path.split("/")[0] if "/" in path else "."


def file_lines(info, paths, cmd):
    lines = []
    for n, path in enumerate(sorted(paths)):
        if n >= MAX_FILES_PER_PAGE:
            lines.append("- (%d more; use `%s query`)" % (len(paths) - n, cmd))
            break
        names = [] if is_test(path) else [x for x, _ in info[path]["symbols"]]
        shown = ", ".join(names[:MAX_SYMBOLS])
        more = " (+%d more)" % (len(names) - MAX_SYMBOLS) if len(names) > MAX_SYMBOLS else ""
        lines.append("- `%s`%s" % (path, " — " + shown + more if shown else ""))
    return lines


RESERVED = re.compile(r"^(con|prn|aux|nul|com[0-9]|lpt[0-9])$", re.IGNORECASE)
IMPORT_LANGS = {"Python", "JavaScript", "TypeScript"}


VAULT_PAGES = "_vault-pages"


def page_names(groups):
    """Group path -> page file name: no two equal ignoring case, none a reserved Windows name."""
    names, used = {}, {VAULT_PAGES.lower()}
    for g in sorted(groups):
        base = "_root" if g == "." else re.sub(r"[^A-Za-z0-9._-]", "_", g.replace("/", "__"))
        if RESERVED.match(base.split(".")[0]):
            base = "_" + base
        name, k = base, 2
        while name.lower() in used:
            name, k = "%s-%d" % (base, k), k + 1
        used.add(name.lower())
        names[g] = name + ".md"
    return names


def make_groups(paths, prefix):
    """Split a directory into groups of at most SPLIT_ABOVE files, by subdirectory."""
    if len(paths) <= SPLIT_ABOVE:
        return {prefix: paths}
    direct, children = [], {}
    depth = prefix.count("/") + 1 if prefix != "." else 0
    for p in paths:
        parts = p.split("/")
        if len(parts) - 1 <= depth:
            direct.append(p)
        else:
            children.setdefault("/".join(parts[: depth + 1]), []).append(p)
    if not children:
        return {prefix: paths}
    groups = {prefix: direct} if direct else {}
    for child in sorted(children):
        groups.update(make_groups(children[child], child))
    return groups


def header(title, cmd):
    return [
        "# " + title,
        "",
        "%s (format %d) from git-tracked files. Do not edit by hand; regenerate with" % (MARKER, FORMAT),
        "`%s build`, check with `%s check`. Symbols are top-level definitions (approximate" % (cmd, cmd),
        "outside Python; none for tests); imports are local only.",
    ]


def render(info, importers, entries, cmd, out_rel, vault=None):
    """Return {relative path: text}: the map page, plus group pages if the repo is large."""
    by_dir = {}
    for path in info:
        by_dir.setdefault(top_dir(path), []).append(path)
    split = len(info) > SPLIT_ABOVE
    sub = posixpath.splitext(out_rel)[0]
    groups = {}
    if split:
        for d in sorted(by_dir):
            groups.update(make_groups(sorted(by_dir[d]), d))
    names = page_names(groups)
    lines = header("Code map", cmd) + ["", "## Directories", ""]
    lines += ["| Directory | Source files | Languages |", "|---|---|---|"]
    for d in sorted(groups or by_dir):
        files = (groups or by_dir)[d]
        langs = ", ".join(sorted({info[p]["lang"] for p in files}))
        cell = "`%s`" % d
        if split:
            cell = "[`%s`](%s/%s)" % (d, posixpath.basename(sub), names[d])
        lines.append("| %s | %d | %s |" % (cell, len(files), langs))
    if entries:
        lines += ["", "## Entry points", ""] + ["- `%s`" % e for e in entries]
    ranked = sorted((p for p in importers if p in info), key=lambda p: (-len(importers[p]), p))
    if ranked:
        lines += ["", "## Most imported (Python, JavaScript and TypeScript local imports)", ""]
        lines += ["- `%s` — imported by %d files" % (p, len(importers[p]))
                  for p in ranked[:TOP_IMPORTED]]
    if vault is not None:
        lines += ["", "## Vault", "",
                  "%d pages; %d broken links; %d orphan pages (no page links to them)."
                  % (len(vault["pages"]), len(vault["broken"]), len(vault["orphans"]))]
        lines += ["- broken: `%s:%d` → %s" % b for b in vault["broken"][:50]]
        lines += ["- orphan: `%s`" % o for o in vault["orphans"][:50]]
        rows = ["| Page | Title | Words | Linked from |", "|---|---|---|---|"]
        rows += ["| `%s` | %s | %d | %d |" % (pg, vault["meta"][pg][0], vault["meta"][pg][1],
                                              vault["inbound"][pg])
                 for pg in vault["pages"]]
        if len(vault["pages"]) > SPLIT_ABOVE:
            pages_name = "%s/%s.md" % (sub, VAULT_PAGES)
            lines += ["", "Vault pages with titles: [vault pages](%s/%s.md); `query` also finds"
                      " pages by path or title." % (posixpath.basename(sub), VAULT_PAGES)]
            vault_page = header("Code map: vault pages", cmd) + [""] + rows
        else:
            lines += ["", "### Vault pages", ""] + rows
            pages_name = None
    pages = {}
    if vault is not None and pages_name:
        pages[pages_name] = "\n".join(vault_page) + "\n"
    if split:
        lines += ["", "Files and symbols per directory are on the linked pages."]
        for d in sorted(groups):
            body = header("Code map: `%s`" % d, cmd) + [""] + file_lines(info, groups[d], cmd)
            pages[sub + "/" + names[d]] = "\n".join(body) + "\n"
    else:
        for d in sorted(by_dir):
            lines += ["", "## `%s`" % d, ""] + file_lines(info, by_dir[d], cmd)
    pages[out_rel] = "\n".join(lines) + "\n"
    return pages


def generated_pages(root, out_rel):
    """Existing files this tool generated: the map page and its directory pages."""
    found = []
    sub = posixpath.splitext(out_rel)[0]
    folder = os.path.join(root, *sub.split("/"))
    if os.path.isdir(folder):
        for name in sorted(os.listdir(folder)):
            rel = sub + "/" + name
            lines = (read_text(root, rel) or "").splitlines()
            if name.endswith(".md") and len(lines) > 2 and lines[2].startswith(MARKER + " (format"):
                found.append(rel)
    return found


