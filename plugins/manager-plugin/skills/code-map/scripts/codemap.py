# Vault links. Markdown pages under the vault folder are scanned outside fenced code blocks:
# [[wikilinks]] resolve by file name across the vault (a path-qualified link by path suffix,
# ties to the shallowest, then first path), [text](page.md) links resolve relative to the page,
# and inline code spans naming a tracked file are recorded as mentions of that file.
# Dead sources (`check` only, beside the broken links): a cited path that no longer exists. A
# link to a non-page file counts as cited, and so does a code span with a `/` that ends in `/` or
# in a file extension, but only when the path's first part is an entry of the repository root or
# a folder name anywhere in the tracked tree (else it likely names another repository's file);
# skipped: fenced code blocks, placeholders (`<`, `>`, `*`, `{`, `$`, `...`, `path/to`, a part
# named foo, bar, baz or holding "example"). A cited path is alive when it is on disk from the
# root, or a tracked path is it or ends with "/" + it (`scripts/x.py`), or, for a folder, holds it.
WIKILINK = re.compile(r"\[\[([^\]|#\\]+?)(?:\\?\|[^\]]*|#[^\]]*)?\]\]")
MD_LINK = re.compile(r"(?<!!)\[[^\]]*\]\(\s*(?:<([^<>\n]+)>|([^)\s]+))(?:\s+[^)]*)?\)")
CODE_SPAN = re.compile(r"`([^`\n]+)`")
FENCE = re.compile(r"^\s{0,3}(`{3,}|~{3,})")


def nfc(text):
    return unicodedata.normalize("NFC", text)


def prose_lines(text):
    fence = None
    for lineno, line in enumerate(text.split("\n"), 1):
        m = FENCE.match(line)
        if fence:
            if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) \
                    and not line.strip()[len(m.group(1)):].strip():
                fence = None
            continue
        if m:
            fence = m.group(1)
            continue
        yield lineno, line


def page_title(text, page):
    lines = text.split("\n")
    if lines and lines[0].strip() == "---":
        for line in lines[1:40]:
            if line.strip() == "---":
                break
            m = re.match(r"^title:\s*['\"]?(.+?)['\"]?\s*$", line)
            if m:
                return m.group(1)
    for _, line in prose_lines(text):
        m = re.match(r"^\s{0,3}#\s+(.+?)\s*#*\s*$", line)
        if m:
            return m.group(1)
    return posixpath.splitext(posixpath.basename(page))[0]


PATH_LIKE = re.compile(r"^[\w.@-]+(?:/[\w.@-]+)*/?$")
CITED_FILE = re.compile(r"/(?:$|[^/]*\.[A-Za-z]\w*$)")


def placeholder_path(ref):
    if re.search(r"[<>*{}$]|\.\.\.|(?:^|/)path/to/", ref):
        return True
    parts = [posixpath.splitext(part)[0].lower() for part in ref.split("/") if part]
    return any(part in ("foo", "bar", "baz") or "example" in part for part in parts)


def dead_sources(root, cited, known):
    """[(page, line, path)] of the cited paths that no longer exist (see the rule above)."""
    tracked = ["/" + f for f in sorted(known)]
    folders = {f.split("/")[0] for f in known}  # the root's entries, then every folder name
    folders.update(part for f in known for part in f.split("/")[:-1])
    dead = []
    for page, lineno, ref in cited:
        if ref.split("/")[0] not in folders:
            continue  # likely another repository's file
        if placeholder_path(ref) or os.path.lexists(os.path.join(root, *ref.split("/"))):
            continue
        if any(("/" + ref) in f if ref.endswith("/") else f.endswith("/" + ref)
               for f in tracked):
            continue  # a tracked path is it, or ends with it
        dead.append((page, lineno, ref))
    return dead


def in_vault(path, vault):
    return vault == "." or path.startswith(vault + "/")


def is_page(path, vault):
    return in_vault(path, vault) and path.lower().endswith(".md")


def strip_dot_slash(ref):
    while ref.startswith("./"):
        ref = ref[2:]
    return ref


def scan_vault(root, vault, files, generated):
    if not vault:
        return None
    pages = sorted(f for f in files if in_vault(f, vault) and f.lower().endswith(".md")
                   and f not in generated and not skipped(f, ""))
    known = set(files)
    by_name = {}
    for f in sorted(known | set(generated)):
        if in_vault(f, vault):
            by_name.setdefault(nfc(posixpath.basename(f)).lower(), []).append(f)
    links, broken, mentions, meta, cited = {p: set() for p in pages}, [], {}, {}, []
    for page in pages:
        text = read_text(root, page) or ""
        meta[page] = (page_title(text, page).replace("|", "/")[:60], len(text.split()))
        for lineno, full_line in prose_lines(text):
            line = CODE_SPAN.sub(" ", full_line)
            for target in WIKILINK.findall(line):
                target = nfc(target.strip())
                cands = []
                for name in (target + ".md", target):  # "Release 1.0" is a page, "a.png" a file
                    found = by_name.get(posixpath.basename(name).lower(), [])
                    if "/" in name:
                        found = [c for c in found
                                 if ("/" + nfc(c).lower()).endswith("/" + name.lower())]
                    if found:
                        cands = found
                        break
                cands.sort(key=lambda c: (c.count("/"), c))
                if cands:
                    links[page].add(cands[0])
                else:
                    broken.append((page, lineno, "[[%s]]" % target))
            for angled, bare in MD_LINK.findall(line):
                target = unquote((angled or bare).split("#")[0])
                if not target or re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I):
                    continue
                dest = posixpath.normpath(posixpath.join(posixpath.dirname(page), target))
                if not target.lower().endswith(".md"):
                    if not dest.startswith("../") and not is_page(dest, vault):
                        mentions.setdefault(dest, set()).add((page, lineno))
                        cited.append((page, lineno, dest))
                    continue
                rooted = posixpath.normpath(posixpath.join("" if vault == "." else vault,
                                                           target.lstrip("/")))
                if dest in known or dest in generated:
                    links[page].add(dest)
                elif rooted in known or rooted in generated:
                    links[page].add(rooted)
                else:
                    broken.append((page, lineno, target))
            for span in CODE_SPAN.findall(full_line):
                ref = strip_dot_slash(span.strip().split("::")[0].split(":")[0])
                if PATH_LIKE.match(ref) and ("/" in ref or "." in ref) and not is_page(ref, vault):
                    mentions.setdefault(ref, set()).add((page, lineno))
                    if CITED_FILE.search(ref) and not ref.startswith("/"):
                        cited.append((page, lineno, ref))
    inbound = {p: 0 for p in pages}
    for page, dests in links.items():
        for d in dests:
            if d in inbound and d != page:
                inbound[d] += 1
    entry = {"index.md", "readme.md", "home.md", "_index.md"}
    orphans = [p for p in pages if not inbound[p] and posixpath.basename(p).lower() not in entry]
    return {"dir": vault, "pages": pages, "broken": broken, "orphans": orphans,
            "mentions": mentions, "meta": meta, "inbound": inbound,
            "dead": lambda: dead_sources(root, cited, known | set(generated))}


def mentions_of(mentions, path):
    """Vault references to a path: the path itself, or a directory that contains it."""
    found = set(mentions.get(path, ()))
    for ref, where in mentions.items():
        if ref.endswith("/") and path.startswith(ref):
            found |= where
        elif ref != path and path.startswith(ref + "/"):
            found |= where
    return sorted(found)


def wikilinked(root, f):
    text = read_text(root, f) or ""
    return any(WIKILINK.search(CODE_SPAN.sub(" ", line)) for _, line in prose_lines(text))


def detect_vault(root, files):
    """(vault dir or None, reason). Deterministic: the same files give the same answer."""
    md = [f for f in files if f.lower().endswith(".md") and not skipped(f, "")]
    if not md:
        return None, "no markdown files"
    if os.path.isdir(os.path.join(root, ".obsidian")):
        return ".", "has .obsidian/ at the root"
    dirs = sorted({posixpath.dirname(f) for f in md if posixpath.dirname(f)})
    prefixes = {"/".join(d.split("/")[:i]) for d in dirs
                for i in range(1, min(3, d.count("/") + 1) + 1)}
    for d in sorted(prefixes, key=lambda d: (d.count("/"), d)):
        if os.path.isdir(os.path.join(root, *d.split("/"), ".obsidian")):
            return d, "has .obsidian/"
    for d in KNOWN_VAULTS:
        inside = [f for f in md if f.startswith(d + "/")]
        if d in STRONG_VAULT_NAMES and inside:
            return d, "known vault folder name"
        if len(inside) >= 3 and any(wikilinked(root, f) for f in inside):
            return d, "known folder name with [[wikilinks]]"
    linked = [f for f in md if wikilinked(root, f)]
    if len(linked) >= 5:
        counts = {}
        for f in linked:
            parts = f.split("/")[:-1]
            for i in range(1, len(parts) + 1):
                counts["/".join(parts[:i])] = counts.get("/".join(parts[:i]), 0) + 1
        best = [d for d, c in counts.items() if c * 10 >= len(linked) * 8]
        if best:
            d = sorted(best, key=lambda d: (-d.count("/"), d))[0]
            return d, "holds most of the %d pages with [[wikilinks]]" % len(linked)
    return None, "no vault found"


class LayoutError(Exception):
    pass


def safe_rel(value, what):
    if value is None:
        return None
    if not isinstance(value, str):
        raise LayoutError("%s in %s must be a string" % (what, CONFIG))
    value = value.replace("\\", "/").strip()
    norm = posixpath.normpath(value) if value else ""
    if not norm or norm.startswith("/") or re.match(r"^[A-Za-z]:", norm) or \
            norm == ".." or norm.startswith("../"):
        if norm != ".":
            raise LayoutError("%s must be a path inside the repository: %r" % (what, value))
    return norm


def foreign_in_map_dir(root, out):
    """Files in the map's page folder that this tool didn't write."""
    folder = os.path.join(root, *posixpath.splitext(out)[0].split("/"))
