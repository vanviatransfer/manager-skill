def module_name(path):
    """`pkg.mod` of `pkg/mod.py`, `pkg` of `pkg/__init__.py`."""
    stem = posixpath.splitext(path)[0]
    if stem.endswith("/__init__") or stem == "__init__":
        stem = stem[: -len("__init__")].rstrip("/")
    return stem.replace("/", ".")


def stored_names(body):
    """The names a block assigns, binds as a loop, `with`, `except` or `case` target, or
    deletes, nested blocks included, the functions and classes it defines not."""
    found, todo = set(), list(body)
    while todo:
        node = todo.pop()
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Lambda)):
            continue
        if isinstance(node, ast.Name) and not isinstance(node.ctx, ast.Load):
            found.add(node.id)
        elif isinstance(node, ast.ExceptHandler) and node.name:
            found.add(node.name)
        elif type(node).__name__ in ("MatchAs", "MatchStar") and node.name:  # `case [x, *y]:`
            found.add(node.name)
        elif type(node).__name__ == "MatchMapping" and node.rest:
            found.add(node.rest)
        todo.extend(ast.iter_child_nodes(node))
    return found


def literal_lookup(node, name):
    """Whether a call or subscript holds the name as a whole string literal (`getattr(x,
    "f")`, `x.__dict__["f"]`, `attrgetter("f")(x)`)."""
    return isinstance(node, (ast.Call, ast.Subscript)) and any(
        isinstance(n, ast.Constant) and n.value == name for n in ast.walk(node))


class CallsFile:
    """One parsed Python file: its definitions by qualified name (`Class.method`, nested ones
    under their function), its top-level names and its import bindings (name -> (spec, the
    imported name)); spec: ("mod", level, dotted) or ("from", level, module, name); and its
    module-level assignments (`alias = core.helper`: name -> the expression assigned)."""

    def __init__(self, path, text, tree):
        self.path, self.lines, self.tree = path, text.split("\n"), tree
        self.defs, self.tops, self.bindings, self.assigns = {}, set(), {}, {}
        self.classes = {}  # qualified class name -> whether it has a base other than object
        self.decorated = set()  # qualified names of the decorated definitions
        self.every = {}  # qualified name -> all its definition nodes (`explore` prints each)
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                self.tops.add(node.name)
            elif isinstance(node, (ast.Assign, ast.AnnAssign)) and node.value is not None:
                for t in node.targets if isinstance(node, ast.Assign) else [node.target]:
                    if isinstance(t, ast.Name):
                        self.assigns[t.id] = node.value
        self.stores = stored_names(tree.body)  # names assigned at module level
        self.collect(tree, [])
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for a in node.names:
                    if a.asname:
                        self.bindings[a.asname] = (("mod", 0, a.name), a.name.split(".")[-1])
                    else:
                        top = a.name.split(".")[0]
                        self.bindings.setdefault(top, (("mod", 0, top), top))
            elif isinstance(node, ast.ImportFrom):
                for a in node.names:
                    if a.name != "*":
                        self.bindings[a.asname or a.name] = (
                            ("from", node.level or 0, node.module or "", a.name), a.name)

    def collect(self, node, stack):
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                qual = ".".join(stack + [child.name])
                self.defs.setdefault(qual, child.lineno)
                self.every.setdefault(qual, []).append(child)
                if child.decorator_list:
                    self.decorated.add(qual)
                if isinstance(child, ast.ClassDef):
                    self.classes[qual] = any(not (isinstance(b, ast.Name) and b.id == "object")
                                             for b in child.bases + child.keywords)
                self.collect(child, stack + [child.name])
            else:
                self.collect(child, stack)


OPERATOR_TOKENS = ("=", "==", "!=", "<", "<=", "<<", "<<=", "<=>", ">", ">=", ">>", ">>=", "+",
                   "++", "+=", "-", "--", "-=", "->", "->*", "*", "*=", "/", "/=", "%", "%=",
                   "^", "^=", "&", "&&", "&=", "|", "||", "|=", "!", "~", ",")


def name_word(name):
    """The pattern of a name as a whole word; an operator's name is not matched when the next
    character continues its token (`operator=` is not in `operator==`; `operator==<T>` is
    `operator==`)."""
    op = name[len("operator"):] if name.startswith("operator") else ""
    more = sorted({t[len(op)] for t in OPERATOR_TOKENS if op and len(t) > len(op)
                   and t.startswith(op)})
    after = "[\\w%s]" % re.escape("".join(more)) if more else "\\w"
    return re.compile(r"(?<!\w)%s(?!%s)" % (re.escape(name), after))


class Calls:
    """The definitions, confident callers and possible references of one name (see
    `references/calls.md`)."""

    def __init__(self, parsed, known, target):
        self.parsed, self.known, self.target = parsed, known, target
        self.name = target.split(".")[-1]
        self.word = name_word(self.name)
        self.definitions, self.callers, self.possible = set(), set(), set()
        self.keys = set()  # (path, qualified name) of the matching definitions
        for path, f in sorted(parsed.items()):
            for qual, line in f.defs.items():
                if qual.split(".")[-1] != self.name:
                    continue
                full = module_name(path) + "." + qual
                if target == self.name or full == target or full.endswith("." + target):
                    self.keys.add((path, qual))
                    self.definitions.add((path, line, qual))
        self.renamed = set()  # every other name the target is bound to, anywhere
        self.aliases = {path: set() for path in parsed}  # per file: such names bound in it
        self.find_aliases()
        self.module_aliases = set(self.renamed)  # `x.<alias>()` counts only for these
        self.failed = set()  # files too deeply nested to walk
        # the classes of matching `__init__`, `__new__`, `__post_init__`: their calls construct
        self.constructs = {(path, qual.rpartition(".")[0]) for path, qual in self.keys
                           if self.name in CONSTRUCTORS and "." in qual
                           and qual.rpartition(".")[0] in parsed[path].classes}
        # a dunder, a method (protocols such as `keys` too), a pytest name or conftest fixture
        self.implicit = (self.name.startswith("__") and self.name.endswith("__")) \
            or self.name.startswith(("test_", "pytest_")) or any(
                qual.rpartition(".")[0] in parsed[path].classes
                or posixpath.basename(path) == "conftest.py" for path, qual in self.keys)
        self.decorated = any(qual in parsed[path].decorated for path, qual in self.keys)
        for path, f in sorted(parsed.items()):
            self.file = f
            self.handled, self.scopes = set(), []
            try:
                self.walk(f.tree, [])
            except RecursionError:
                self.failed.add(path)

    def find_aliases(self):
        """The import bindings and module-level assignments that give the target another name:
        those that resolve to a matching definition, and those whose imported or assigned name
        is the target's or an alias found so far; and, the other way, the name such a binding of
        the target's or an alias's name imports or assigns (until no more are found)."""
        while True:
            before = len(self.renamed)
            for path, f in sorted(self.parsed.items()):
                self.file = f
                spelled = self.renamed | {self.name}
                found = [b for b, (spec, orig) in f.bindings.items() if orig in spelled
                         or self.canonical(self.spec(path, spec)) in self.keys]
                for a, value in f.assigns.items():
                    word = value.id if isinstance(value, ast.Name) else getattr(value, "attr", "")
                    if word in spelled or self.canonical(("sym", path, a)) in self.keys \
                            or any(literal_lookup(value, w) for w in spelled):
                        found.append(a)
                for b, (spec, orig) in f.bindings.items():  # `import x as <name>`: x too
                    if b in spelled and orig != self.name:
                        self.renamed.add(orig)
                for a, value in f.assigns.items():
                    if not isinstance(value, (ast.Name, ast.Attribute)):
                        continue
                    word = value.id if isinstance(value, ast.Name) else value.attr
                    if a in spelled and word != self.name:
                        self.renamed.add(word)
                for b in found:
                    if b != self.name:
                        self.renamed.add(b)
                        self.aliases[path].add(b)
            if len(self.renamed) == before:
                return

    def module(self, path, level, dotted):
        return resolve_python(path, level, dotted.strip("."), self.known) \
            if dotted.strip(".") or level else None

    def spec(self, path, spec):
        """A binding's spec as ("mod", path, level, dotted), ("sym", path, qual) or None."""
        if spec[0] == "mod":
            return ("mod", path, spec[1], spec[2])
        _, level, mod, name = spec
        sub = (mod + "." + name).strip(".")
        if self.module(path, level, sub):
            return ("mod", path, level, sub)
        where = self.module(path, level, mod)
        return ("sym", where, name) if where else None

    def attribute(self, ref, attr):
        if ref is None:
            return None
        if ref[0] == "sym":
            return ("sym", ref[1], ref[2] + "." + attr)
        _, path, level, dotted = ref
        sub = (dotted + "." + attr).strip(".")
        if self.module(path, level, sub):
            return ("mod", path, level, sub)
        where = self.module(path, level, dotted)
        return ("sym", where, attr) if where else ("mod", path, level, sub)

    def canonical(self, ref, depth=0):
        """(path, qualified name) a symbol reference ends at, following re-exports (`from x
        import f` in the file it names) up to 8 steps, or None."""
        if ref is None or ref[0] != "sym":
            return None
        path, qual = ref[1], ref[2]
        f = self.parsed.get(path)
        first, _, rest = qual.partition(".")
        if f is None or first in f.tops or depth >= 8 \
                or (first not in f.bindings and first not in f.assigns):
            return path, qual
        if first in f.bindings:
            found = self.spec(path, f.bindings[first][0])
        else:  # `alias = core.helper` at module level
            here, self.file = self.file, f
            found = self.resolve(f.assigns[first], [])
            self.file = here
        for part in rest.split(".") if rest else ():
            found = self.attribute(found, part)
        return self.canonical(found, depth + 1)

    def resolve(self, node, stack):
        """What an expression names, as for `spec`, or None when it can't tell."""
        f = self.file
        if isinstance(node, ast.Name):
            if node.id in ("self", "cls"):
                classes = [i for i, (kind, _) in enumerate(stack) if kind == "class"]
                if classes:
                    return ("sym", f.path, ".".join(n for _, n in stack[: classes[-1] + 1]))
            for i in range(len(stack), 0, -1):  # an enclosing function's own definitions
                if stack[i - 1][0] == "def":
                    qual = ".".join([n for _, n in stack[:i]] + [node.id])
                    if qual in f.defs:
                        return ("sym", f.path, qual)
            if node.id in f.bindings:
                return self.spec(f.path, f.bindings[node.id][0])
            if node.id in f.tops or node.id in f.assigns:
                return ("sym", f.path, node.id)
            return None
        if isinstance(node, ast.Attribute):
            return self.attribute(self.resolve(node.value, stack), node.attr)
        return None

    def ident(self, node):
        """The word naming the target in this Name or Attribute, an alias note, or None."""
        if isinstance(node, ast.Attribute):
            if node.attr == self.name:
                return ""
            return " (alias %s)" % node.attr if node.attr in self.module_aliases else None
        if isinstance(node, ast.Name):
            if node.id == self.name:
                return ""
            if node.id in self.aliases[self.file.path]:
                return " (alias %s)" % node.id
        return None

    def line_of(self, node, first=None, last=None):
        """The line of the word in node's lines, from the first; else node's first line."""
        first = first or node.lineno
        last = last or getattr(node, "end_lineno", None) or first
        for n in range(first, last + 1):
            if n - 1 < len(self.file.lines) and self.word.search(self.file.lines[n - 1]):
                return n
        return first

    def where(self, stack):
        return ".".join(n for _, n in stack) or MODULE_LEVEL

    def add(self, node, kind, line=None):
        self.possible.add((self.file.path, line or self.line_of(node), kind))

    def walk(self, node, stack):
        f = self.file
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            qual = ".".join([n for _, n in stack] + [node.name])
            if node.name == self.name and (f.path, qual) not in self.keys:
                self.add(node, "other definition", node.lineno)
            for d in node.decorator_list:
                if self.ident(d) is not None:
                    self.add(d, "decorator", self.end_line(d))
                    self.handled.add(id(d))
            inner = stack + [("class" if isinstance(node, ast.ClassDef) else "def", node.name)]
            if isinstance(node, ast.ClassDef):  # names its body assigns (seen by its methods
                self.scopes.append(stored_names(node.body))  # too here: on the safe side)
            else:  # its parameters and assigned names
                a = node.args
                params = a.posonlyargs if hasattr(a, "posonlyargs") else []
                params = params + a.args + a.kwonlyargs + [x for x in (a.vararg, a.kwarg) if x]
                self.scopes.append({x.arg for x in params} | stored_names(node.body))
            for field, value in ast.iter_fields(node):
                for child in value if isinstance(value, list) else [value]:
                    if isinstance(child, ast.AST):
                        self.walk(child, inner if field == "body" else stack)
            self.scopes.pop()
            return
        if isinstance(node, ast.Lambda):
            a = node.args
            params = (a.posonlyargs if hasattr(a, "posonlyargs") else []) + a.args + \
                a.kwonlyargs + [x for x in (a.vararg, a.kwarg) if x]
            self.scopes.append({x.arg for x in params})
            for child in ast.iter_child_nodes(node):
                self.walk(child, stack)
            self.scopes.pop()
            return
        if isinstance(node, ast.Call):
            func = node.func
            note = self.ident(func)
            if self.constructs and isinstance(func, (ast.Name, ast.Attribute)) \
                    and self.canonical(self.resolve(func, stack)) in self.constructs:
                self.add(func, "constructor call", self.end_line(func))
            if note is not None:
                self.handled.add(id(func))
                line = self.end_line(func)
                base = func
                while isinstance(base, ast.Attribute):
                    base = base.value
                shadowed = isinstance(base, ast.Name) and (base is func or base.id not in (
                    "self", "cls")) and (any(base.id in scope for scope in self.scopes)
                                         or base.id in f.stores)
                kind = "attribute call" if isinstance(func, ast.Attribute) else "call"
                if shadowed and self.resolve(func, stack) is not None:  # it may be another
                    self.add(func, kind + (note or " (shadowed)"), line)  # object here
                elif not shadowed and self.canonical(self.resolve(func, stack)) in self.keys:
                    self.callers.add((f.path, line, self.where(stack)))
                else:
                    self.add(func, kind + note, line)
            if isinstance(func, ast.Name) and func.id in ATTR_CALLS and len(node.args) >= 2:
                arg = node.args[1]
                if isinstance(arg, ast.Constant) and arg.value == self.name:
                    self.handled.add(id(arg))
                    self.add(arg, func.id)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)) and node.value is not None \
                and (self.ident(node.value) is not None  # `h = helper` in any scope
                     or literal_lookup(node.value, self.name)):  # `h = getattr(m, "helper")`
            named = self.ident(node.value) is not None
            for t in node.targets if isinstance(node, ast.Assign) else [node.target]:
                if isinstance(t, ast.Name) and t.id != self.name:
                    self.renamed.add(t.id)
                    self.aliases[f.path].add(t.id)
                    self.handled.add(id(t))  # listed once, as `renamed to`
                    if not named:
                        self.add(node.value, "renamed to %s" % t.id)
                    elif id(node.value) not in self.handled:  # followed: no `reference`
                        self.handled.add(id(node.value))
                        self.add(node.value, "renamed to %s" % t.id, self.end_line(node.value))
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            words = [w for a in node.names for w in a.name.split(".") + [a.asname]]
            if self.name in words + (getattr(node, "module", None) or "").split("."):
                self.add(node, "import")
            for alias in sorted(self.aliases[f.path].intersection(words)):
                self.add(node, "import (alias %s)" % alias, node.lineno)
        elif id(node) not in self.handled:
            note = self.ident(node) if isinstance(node, (ast.Name, ast.Attribute)) else None
            if note is not None:
                store = isinstance(node.ctx, ast.Store)
                kind = "assignment" if store else (
                    "attribute reference" if isinstance(node, ast.Attribute) else "reference")
                self.add(node, kind + note, self.end_line(node))
            elif isinstance(node, ast.Constant) and isinstance(node.value, str) \
                    and self.word.search(node.value):
                last = getattr(node, "end_lineno", None) or node.lineno
                lines = [n for n in range(node.lineno, last + 1) if n - 1 < len(f.lines)
                         and self.word.search(f.lines[n - 1])]
                for n in lines or [node.lineno]:
                    self.add(node, "string", n)
        for child in ast.iter_child_nodes(node):
            self.walk(child, stack)

    def end_line(self, node):
        """An Attribute's name is on its last line, a Name's on its only one."""
        if isinstance(node, ast.Attribute):
            return getattr(node, "end_lineno", None) or node.lineno
        return node.lineno


def calls_parse(root, files):
    """({path: CallsFile}, [not parsed: (path, why)]) of the map's Python files."""
    parsed, failed = {}, []
    for path in files:
        ext = posixpath.splitext(path)[1].lower()
        if ext not in (".py", ".pyw") and (ext or posixpath.basename(path).startswith(".")):
            continue
        text = read_text(root, path)
        if not ext:  # an extensionless script: Python when its first line says so
            if text is None or not PY_SHEBANG.match(text):
                continue
        if text is None:
            failed.append((path, "unreadable, too large or not text"))
            continue
        text = text[1:] if text.startswith("\ufeff") else text  # a UTF-8 byte order mark
        try:
            with warnings.catch_warnings():  # the repository's `"\d"` and such: not ours to warn
                warnings.simplefilter("ignore")
                tree = ast.parse(text, filename=path)
        except SyntaxError as exc:
            nested = "too many nested" in str(exc.msg) or "too complex" in str(exc.msg)
            failed.append((path, "nested too deeply" if nested
                           else "syntax error, line %s" % exc.lineno))
            continue
        except RecursionError:
            failed.append((path, "nested too deeply"))
            continue
        except (ValueError, MemoryError):
            failed.append((path, "cannot be parsed by this Python"))
            continue
        try:
            parsed[path] = CallsFile(path, text, tree)
        except RecursionError:
            failed.append((path, "nested too deeply"))
    return parsed, failed


def text_line(found, total, shown, unparsed, capped, unread, other=0, extra=(), cpp=False):
    """The `text:` line: the counts, each reason that applies, then `grep the rest`. It never
    says every occurrence is listed: a static scan can't know that. `other`: the occurrences in
    files not parsed as Python (config, notebooks, templates, other languages); `cpp`: a name
    defined in C/C++ only, `other` then counts the files neither Python nor C/C++."""
    line = "text: %d occurrence%s of %s, %d on lines listed above" % (
        total, "" if total == 1 else "s", found.name, shown)
    if found.renamed:
        line += "; renamed: %s" % ", ".join(sorted(found.renamed))
    stored = sum(1 for _, _, kind in found.possible
                 if kind.split(" (")[0] in ("reference", "attribute reference"))
    if stored and cpp:  # C/C++: a type, a qualifier, a pointer or a value taken
        line += "; named without a call at %d place%s, calls through %s not followed" % (
            stored, "" if stored == 1 else "s", "it" if stored == 1 else "them")
    elif stored:
        line += "; passed or stored at %d place%s, calls through %s not followed" % (
            stored, "" if stored == 1 else "s", "it" if stored == 1 else "them")
    if found.possible:
        line += "; %d possible" % len(found.possible)
    if found.implicit:
        line += "; called implicitly (operators, protocols, base classes, frameworks)"
    if found.decorated:
        line += "; decorated: may be registered and called through its decorator"
    for reason in extra:  # C/C++ (`cpp_calls`)
        line += "; " + reason
    if other:
        line += ("; %d in other files (not parsed: docs, config, other languages)" if cpp
                 else "; %d in files not parsed as Python") % other
    if unparsed:
        line += "; %d Python file%s not parsed" % (unparsed, "" if unparsed == 1 else "s")
    if unread:
        line += ("; %d tracked file%s not read (sensitive, vendored or skipped, symlinks, too "
                 "large or not text)" % (unread, "" if unread == 1 else "s"))
    if capped:
        line += "; cut (rerun with --all)"
    return line + "; grep the rest"


C_BINDING = re.compile(r"\b(?:(?:Bind|Add|AddUnique|Create|Remove)(?:UObject|UFunction|Dynamic|Raw|"
                       r"SP|ThreadSafeSP|Static|Lambda|WeakLambda)|Bind(?:Action|Axis|Key|Touch|"
                       r"Vector)|SetTimer)\b")


TYPED = {}  # `calls` / `explore` names typed with `::`: {as matched (`A.b`): as typed (`A::b`)}


def typed(target):
    return TYPED.get(target, target)


def shell_word(name):
    """A name as a shell word: quoted when it holds more than letters, digits, `_`, `.`, `:`
    (`'operator bool'`, `'~Widget'`, `'operator[]'`); names never hold a quote."""
    return "'%s'" % name if re.search(r"[^\w.:]", name) else name


def grep_hint(name):
    """`grep -n -w name`; a name with other characters is matched as fixed text (`-F`)."""
    return ("grep -n -F -w %s" if re.search(r"\W", name) else "grep -n -w %s") % shell_word(name)


def cpp_matches(target, cfiles):
    """The C/C++ symbols a name as `calls` takes it names, sorted by path and line; a
    declaration whose definition matches too is left out (the definition names it)."""
    found = []
    for path in sorted(cfiles):
        for s in cfiles[path].symbols:
            if not qualifies(target, path, ".".join(s["qual"])):
                continue
            if "." not in target and s["qual"][-2:-1] == [s["name"]]:
                continue  # a constructor: `X` names the class, `X::X` the constructor
            if s["decl"] and any(qualifies(target, d["path"], ".".join(d["qual"]))
                                 for d in s.get("defined", ())):
                continue
            found.append(s)
            found += [d for d in s.get("defined", ()) if d["name"] != s["name"]]  # X_Implementation
    return sorted({id(s): s for s in found}.values(), key=lambda s: (s["path"], s["line"]))


def cpp_where(symbols, limit=3):
    more = " (+%d more)" % (len(symbols) - limit) if len(symbols) > limit else ""
    return ", ".join("%s:%d" % (d["path"], d["line"]) for d in symbols[:limit]) + more


def cpp_note(s):
    """` [tag] (declared a.h:3)`: what `explore` and `calls` say after a C/C++ symbol's name."""
    tag = s["tag"] or s.get("inherited", "")
    note = " [%s]" % tag if tag else ""
    bodies = sorted({d["name"] for d in s.get("defined", ()) if d["name"] != s["name"]})
    if s.get("declared"):
        note += " (declared %s)" % cpp_where(s["declared"])
    elif bodies:  # an Unreal RPC or native event: `X_Implementation`, `X_Validate`
        note += " (bodies: %s)" % ", ".join(bodies)
    elif s["decl"] and s["kind"] != "log category":
        note += " (no definition in the files read)"
    return note


def cpp_implicit(target, matches=()):
    """Why calls to a C++ operator, destructor or constructor go unseen, or "" for other names.
    """
    name = re.split(r"\.|::", target)[-1]
    if re.match(r"operator(?=\W)", name):
        return ("operators are mostly called implicitly, as in `a == b`, `a[i]` or a "
                "conversion: those calls are not seen")
    if name.startswith("~"):
        return ("destructors run implicitly, at scope exit or on `delete`: those calls are not "
                "seen")
    if any(s["qual"][-2:-1] == [s["name"]] for s in matches):
        return ("constructors run implicitly, on a declaration, `new`, a copy or a "
                "conversion: those calls are not seen")
    return ""


def cpp_calls(found, target, cfiles):
    """Add the C/C++ definitions and text occurrences of a name to a `Calls` result (nothing is
    resolved: every occurrence is `possible`). Returns (the declaration lines named by a
    definition line, the reasons for the `text:` line); ((), []) when C/C++ has none."""
    matches = cpp_matches(target, cfiles)
    named, other = set(), set()
    for s in matches:
        found.definitions.add((s["path"], s["line"], "%s (%s %s)%s" % (
            "::".join(s["qual"]), LANG[posixpath.splitext(s["path"])[1].lower()], s["kind"],
            cpp_note(s))))
        named.update((d["path"], d["line"]) for d in s.get("declared", ()))
    keys = {(s["path"], s["line"]) for s in matches} | named
    for path, cf in cfiles.items():
        other.update((path, s["line"]) for s in cf.symbols
                     if s["name"] == found.name and (path, s["line"]) not in keys)
    bound = dead = 0
    for path in sorted(cfiles):
        cf = cfiles[path]
        for n, (raw, code) in enumerate(zip(cf.lines, cf.code), 1):
            if (path, n) in keys or not found.word.search(raw):
                continue
            if n - 1 in cf.dead:
                dead += 1
                continue
            binding = C_BINDING.search(raw)
            for m in found.word.finditer(code):
                before, after = code[:m.start()].rstrip(), code[m.end():].lstrip()
                if (path, n) in other:
                    kind = "other definition"
                elif code.lstrip().startswith("#"):
                    kind = "macro"
                elif binding:
                    kind = "delegate binding (%s)" % binding.group()
                elif after.startswith("(") or after.startswith("<"):
                    kind = "member call" if before.endswith((".", "->")) else (
                        "qualified call" if before.endswith("::") else "call")
                else:
                    kind = "reference"
                found.possible.add((path, n, kind))
                bound += kind.startswith("delegate")
                break
            else:  # only in a string or a comment
                for m in found.word.finditer(raw):
                    if code[m.start():m.end()].strip():
                        continue
                    if code[:m.start()].count('"') % 2:  # inside a string literal
                        kind = "delegate binding by name (%s)" % binding.group() if binding \
                            else "string"
                        found.possible.add((path, n, kind))
                        bound += bool(binding)
                        break
    found.cpp_implicit = cpp_implicit(target, matches)
    if not matches and not any(p in cfiles for p, _, _ in found.possible):
        return (), []
    reasons = ["C/C++ not resolved: overloads, templates, macros, virtual dispatch, function "
               "pointers and delegates"] + ([found.cpp_implicit] if found.cpp_implicit else [])
    if dead:
        reasons.append("%d line%s in `#if 0` blocks, not listed" % (dead, "" if dead == 1 else "s"))
    if bound:
        reasons.append("bound to a delegate or timer at %d place%s (called through it)"
                       % (bound, "" if bound == 1 else "s"))
    if any((s["tag"] or s.get("inherited", "")).startswith("UFUNCTION") for s in matches):
        reasons.append("UFUNCTION: may be called by reflection or from Blueprints (assets are "
                       "not read)")
    return named, reasons


def calls_lines(root, targets, tracked, out_rel, everything=False, links=0):
    """The lines `calls` prints; see `references/calls.md`. `tracked`: the tracked files (no
    symlinks; `links`: how many were left out)."""
    files = [f for f in tracked if not skipped(f, out_rel)]
    parsed, failed = calls_parse(root, files)
    known = set(files)
    texts, unread = {}, links + sum(1 for f in tracked if skipped(f, out_rel)
                                    and not is_map_page(f, out_rel))  # secrets are never read
    for path in files:
        if not is_map_page(path, out_rel):
            text = read_text(root, path)
            if text is not None:
                texts[path] = text.split("\n")
            elif path not in dict(failed):  # a .py one is under `not parsed`
                unread += 1
    out, deep, bad = [], set(), dict(failed)  # bad: Python files, counted on their own
    cfiles = cpp_parse(root, files)[0] if any(f.lower().endswith(C_EXT) for f in files) else {}
    for target in targets:
        found = Calls(parsed, known, target)
        deep |= found.failed
        python_defs = len(found.definitions)
        named, extra = cpp_calls(found, target, cfiles) if cfiles else ((), [])
        implicit = getattr(found, "cpp_implicit", "")
        cpp_only = bool(extra) and not python_defs  # its definitions are C/C++ ones only
        all_cpp = cpp_only if target == targets[0] else all_cpp and cpp_only
        listed, capped = set(named), False
        out.append("calls %s" % typed(target))
        code_first = sorted(found.possible, key=lambda i: (i[2] == "string", i))
        for head, items, show in (
                ("definitions", sorted(found.definitions), lambda i: "%s:%d %s" % i),
                ("callers", sorted(found.callers), lambda i: "%s:%d in %s" % i),
                ("possible", code_first, lambda i: "%s:%d %s" % i)):
            if not items and head == "callers" and extra:
                out.append("callers: not resolved for C/C++ (possible: lists its text "
                           "occurrences)")
                continue
            if not items:
                out.append("%s: none found%s" % (head, " (%s)" % implicit
                                                 if implicit and head == "possible" else ""))
                continue
            out.append("%s:" % head)
            keep = items if everything or len(items) <= CALLS_LIMIT else items[:CALLS_LIMIT]
            for item in keep:
                out.append("  " + show(item))
                listed.add(item[:2])
            if len(keep) < len(items):
                capped = True
                out.append("  … %d more (rerun with --all)" % (len(items) - len(keep)))
        total = shown = other = 0
        for path in sorted(texts):
            python = path in parsed or path in bad
            for n, line in enumerate(texts[path], 1):
                hits = len(found.word.findall(line))
                total += hits
                if hits and (path, n) in listed:
                    shown += hits
                if not python and not (cpp_only and path in cfiles):
                    other += hits
        out.append(text_line(found, total, shown, len(failed) + len(found.failed), capped,
                             unread, other, list(extra) + (
                                 [implicit] if implicit and implicit not in extra else []),
                             cpp_only))
        stopped = cpp_stopped_note(cfiles, found.word)
        if stopped:
            out.append(stopped)
    failed = failed + [(path, "nested too deeply") for path in sorted(deep)]
    if failed:
        out.append("not parsed: " + ", ".join("%s (%s)" % item for item in sorted(failed)))
    out.append(CPP_COVERAGE if targets and all_cpp else CALLS_COVERAGE)
    return out


# `explore`: the source of named definitions, live from the working tree (see
# `references/explore.md`). It reuses the `calls` parse and resolution and writes nothing.
EXPLORE_BUDGET = 8000  # printed characters by default (`--budget`: characters, not tokens)
EXPLORE_CALLERS = 10  # the resolved callers shown per name; `calls <name>` lists them all
EXPLORE_FILES = 3  # definitions in more than this many files: headers only
EXPLORE_APPROX = 300  # the most lines an approximate (not `ast`) range spans
EXPLORE_MEMBERS = 40  # the members listed for a class too big to show
EXPLORE_CUTS = 40  # the `cut:` lines listed, then one count
EXPLORE_NEAR = 5  # near matches for a name with no definition
EXPLORE_CURRENT = ("the source above is the working tree now: Read a range again only before "
                   "an Edit of it")
EXPLORE_INEXACT = ("the source above is the working tree now, but not byte-exact (bytes that "
                   "are not UTF-8 or control characters print as U+FFFD or ?): Read the range "
                   "before an Edit of it")
NO_SYMBOLS = (set(LANG) - set(PATTERN_KEY) - {".py"} - set(C_EXT)) | {".pyi"}  # grep them
SOURCE_LINE = re.compile(r"^ *\d+\t")  # a line of `explore_source`
KIND_WORD = re.compile(r"\b(function|class|interface|type|enum|const|let|var|func|struct|trait|"
                       r"fn|mod|module|def|protocol|actor|object|record)\b")
CONTROL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")  # a tab is kept: it is in the line format
AST_LINES = re.compile(r"\r\n|\r|\n")  # the line breaks `ast` counts (a lone `\r` too)
LONE_CR = re.compile(r"\r(?!\n)")


def qualifies(target, path, qual):
    """Whether a name as `calls` takes it (`f`, `mod.f`, `Class.m`) names this definition."""
    full = module_name(path) + "." + qual
    return qual.split(".")[-1] == target.split(".")[-1] and (
        target == qual.split(".")[-1] or full == target or full.endswith("." + target))


def approx_end(lines, symbols, line, cap=EXPLORE_APPROX):
    """(end, capped) of a definition found by line pattern: the line before the next symbol of
    its file at the same or lower indentation, or the end of the file, trailing blank lines
    left out; capped: no end within `cap` lines (end is then the last of those)."""
    def indent(n):
        text = lines[n - 1] if n - 1 < len(lines) else ""
        return len(text) - len(text.lstrip())
    end = len(lines)
    for _, other in sorted(symbols, key=lambda s: s[1]):
        if other > line and indent(other) <= indent(line):
            end = other - 1
            break
    while end > line and not lines[end - 1].strip():
        end -= 1
    return (line + cap - 1, True) if end - line + 1 > cap else (end, False)


def python_entry(path, f, node, qual, lines):
    """One definition node of a parsed file; `lines`: the file split as `ast` counts lines."""
    start = min([d.lineno for d in node.decorator_list] + [node.lineno])
    parent = qual.rpartition(".")[0]
    kind = "class" if isinstance(node, ast.ClassDef) else (
        "method" if parent in f.classes else "function")
    if isinstance(node, ast.AsyncFunctionDef):
        kind = "async " + kind
    sig, first = node.lineno, node.lineno
    if node.body:
        stmt = node.body[0]
        first = min([d.lineno for d in getattr(stmt, "decorator_list", [])] + [stmt.lineno])
        text = lines[stmt.lineno - 1] if stmt.lineno - 1 < len(lines) else ""
        if first == stmt.lineno and text.encode("utf-8")[:stmt.col_offset].decode(
                "utf-8", "replace").strip():  # `):  return x`: the signature ends there
            sig = first
        else:
            sig = max(node.lineno, first - 1)
    members = []
    if isinstance(node, ast.ClassDef):  # each member node once, also two of one name
        for child in member_nodes(node):
            members.append(python_entry(path, f, child, qual + "." + child.name, lines))
    return {"path": path, "start": start, "end": node.end_lineno, "kind": kind, "name": qual,
            "lines": lines, "sig": sig, "members": members, "note": "", "lang": "Python",
            "body": first, "capped": False}


def member_nodes(node):
    """The definitions a class body holds, also under `if`, `try`, `with` (as `collect` finds
    them), each once, in line order."""
    found, todo = [], list(node.body)
    while todo:
        child = todo.pop()
        if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            found.append(child)
        else:
            todo.extend(ast.iter_child_nodes(child))
    return sorted(found, key=lambda n: (n.lineno, n.col_offset))


def pattern_entry(path, lang, lines, symbols, name, line, note=""):
    end, capped = approx_end(lines, symbols, line)
    m = KIND_WORD.search(lines[line - 1]) if line - 1 < len(lines) else None
    kind = m.group(1) if m else "definition"
    kind = "function" if kind in ("def", "fn", "func") else kind
    note = "end approximate%s%s" % (
        "; end not found within %d lines" % EXPLORE_APPROX if capped else "", note)
    return {"path": path, "start": line, "end": end, "kind": kind, "name": name,
            "lines": lines, "sig": line, "members": [], "note": " (%s)" % note,
            "lang": lang, "body": line + 1, "capped": capped}


def cpp_entry(cf, s):
    """The `explore` entry of a C/C++ symbol: its brace-matched range, or an approximate one
    (as `pattern_entry`) when the file's braces don't balance."""
    note, end, capped, members = cpp_note(s), s["end"], False, []
    if not cf.clean or end is None:
        tops = [(x["name"], x["line"]) for x in cf.symbols if x["parent"] is None]
        end, capped = approx_end(cf.lines, tops, s["line"])
        note += " (end approximate: braces do not balance in this file%s%s)" % (
            "; scan stopped at line %d" % cf.stopped if cf.stopped else "",
            "; end not found within %d lines" % EXPLORE_APPROX if capped else "")
    else:
        for m in s["members"]:
            where = "; ".join("defined %s:%d-%d" % (d["path"], d["start"], d["end"] or d["line"])
                              for d in m.get("defined", ())[:3])
            members.append({"start": m["start"], "end": m["end"], "kind": m["kind"],
                            "name": "::".join(m["qual"]),
                            "note": " (%s)" % where if where else ""})
    sig = min(max(s["sig"], s["start"]), end)
    return {"path": cf.path, "start": s["start"], "end": end, "kind": s["kind"],
            "name": "::".join(s["qual"]), "lines": cf.lines, "sig": sig, "members": members,
            "note": note, "lang": LANG[posixpath.splitext(cf.path)[1].lower()],
            "body": min(sig + 1, end), "capped": capped}


def explore_header(e):
    note = e["note"] + e.get("cr", "")
    if e["end"] > len(e["lines"]):  # never a range the file doesn't hold, unsaid
        note += " (past the end of the file: it has %d lines)" % len(e["lines"])
    return CONTROL.sub("?", "%s:%d-%d %s %s%s" % (e["path"], e["start"], e["end"], e["kind"],
                                                  e["name"], note)).replace("\t", "?")


