#!/usr/bin/env python3
"""codemap: a deterministic, dependency-free map of a repository's code.

Usage:
  codemap.py build [--root DIR] [--out PATH]   write the map (default docs/vault/map.md)
  codemap.py check [--root DIR] [--out PATH]   exit 0 if the map is current, 1 if stale
  codemap.py query TERM [--root DIR]           where TERM is defined, which paths match it,
                                               who imports them, which vault pages mention them
  codemap.py mentions [PATH...] [--base SHA]   vault pages that mention these files (or the
                                               files changed since SHA)
  codemap.py detect [--root DIR]               where the vault and the map are, and why

The vault and map locations come from .codemap.json at the repository root. Without it they
are detected (a folder with .obsidian/, a known vault folder name, or the folder holding most
pages with [[wikilinks]]); the first build writes .codemap.json so later runs agree. An existing
hand-written map.md is never overwritten: the map then goes to code-map.md.

Only the Python standard library is used (Python 3.8+). Files come from `git ls-files`, so
ignored files are skipped. Symbols are top-level definitions found with the `ast` module for
Python and with line patterns for other languages (approximate). Nothing is executed and
nothing is sent anywhere.
"""
import argparse
import ast
import json
import os
import posixpath
import re
import subprocess
import sys
import unicodedata

FORMAT = 1
CONFIG = ".codemap.json"
NO_VAULT_MAP = "docs/code-map.md"
KNOWN_VAULTS = ("docs/vault", "vault", "docs/knowledge", "knowledge", "docs/wiki", "wiki",
                "docs/notes", "notes", "kb", "docs/kb")
MAX_VAULT_ROWS = 400
MAX_BYTES = 512 * 1024
MAX_SYMBOLS = 6
SPLIT_ABOVE = 150
MAX_FILES_PER_PAGE = 800
MARKER = "Generated by code-map"
TOP_IMPORTED = 15

SKIP_DIRS = {
    "node_modules", "vendor", "third_party", "dist", "build", "out", "target", ".venv",
    "venv", "__pycache__", ".git", ".next", ".nuxt", "coverage", "bin", "obj",
}
SKIP_SUFFIXES = (".min.js", ".min.css", ".map", ".lock", ".snap")
# Files that may hold secrets are never read (patterns after graphify's detect.py).
SENSITIVE = re.compile(r"(^|/)(\.env(\..*)?|\.envrc|id_(rsa|dsa|ecdsa|ed25519)(\.pub)?|\.netrc|"
                       r"\.npmrc|\.pypirc|\.git-credentials)$|\.(pem|key|p12|pfx|crt|der|p8)$|"
                       r"(^|/)(secrets?|credentials?)(/|\.)", re.IGNORECASE)

LANG = {
    ".py": "Python", ".js": "JavaScript", ".jsx": "JavaScript", ".mjs": "JavaScript",
    ".cjs": "JavaScript", ".ts": "TypeScript", ".tsx": "TypeScript", ".go": "Go",
    ".java": "Java", ".kt": "Kotlin", ".kts": "Kotlin", ".cs": "C#", ".rs": "Rust",
    ".php": "PHP", ".rb": "Ruby", ".swift": "Swift", ".c": "C", ".h": "C/C++",
    ".cpp": "C++", ".cc": "C++", ".hpp": "C++", ".scala": "Scala", ".dart": "Dart",
    ".vue": "Vue", ".svelte": "Svelte", ".sql": "SQL", ".sh": "Shell", ".ps1": "PowerShell",
}
JS_EXT = (".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx")

PATTERNS = {
    "js": [re.compile(r"^export\s+(?:default\s+)?(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?"
                      r"(?:function\*?|class|const|let|var|interface|type|enum)\s+([A-Za-z_$][\w$]*)")],
    "go": [re.compile(r"^func\s+(?:\([^)]*\)\s*)?([A-Z]\w*)"),
           re.compile(r"^type\s+([A-Z]\w*)")],
    "jvm": [re.compile(r"^\s*(?:public\s+|internal\s+)?(?:(?:abstract|final|static|sealed|partial|"
                       r"data|open)\s+)*(?:class|interface|enum|record|object|struct)\s+(\w+)")],
    "rs": [re.compile(r"^pub\s+(?:async\s+)?(?:fn|struct|enum|trait|type|mod)\s+(\w+)")],
    "php": [re.compile(r"^\s*(?:abstract\s+|final\s+)?(?:class|interface|trait|enum)\s+(\w+)"),
            re.compile(r"^function\s+(\w+)")],
    "rb": [re.compile(r"^\s*(?:class|module)\s+([A-Z][\w:]*)"),
           re.compile(r"^def\s+(?:self\.)?(\w+[?!]?)")],
    "swift": [re.compile(r"^(?:public\s+|open\s+)?(?:final\s+)?(?:class|struct|enum|protocol|"
                         r"actor|func)\s+(\w+)")],
}
PATTERN_KEY = {
    ".js": "js", ".jsx": "js", ".mjs": "js", ".cjs": "js", ".ts": "js", ".tsx": "js",
    ".go": "go", ".java": "jvm", ".kt": "jvm", ".kts": "jvm", ".cs": "jvm", ".scala": "jvm",
    ".rs": "rs", ".php": "php", ".rb": "rb", ".swift": "swift",
}
JS_IMPORT = re.compile(r"""(?:\bfrom\s+|\bimport\s+|\brequire\s*\(\s*|\bimport\s*\(\s*)['"](\.{1,2}/[^'"]+)['"]""")
TEST_DIRS = {"test", "tests", "__tests__", "spec", "specs", "testdata", "fixtures"}
TEST_FILE = re.compile(r"(^test_|_test\.|\.test\.|\.spec\.|Tests?\.)")
ENTRY_NAMES = {"main", "index", "app", "server", "cli", "__main__", "manage", "program"}


def git_files(root):
    try:
        out = subprocess.run(["git", "-C", root, "ls-files", "-z"], capture_output=True, check=True)
        files = [f for f in out.stdout.decode("utf-8", "replace").split("\0") if f]
    except (OSError, subprocess.CalledProcessError):
        files = []
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for name in filenames:
                rel = os.path.relpath(os.path.join(dirpath, name), root)
                files.append(rel.replace(os.sep, "/"))
    return sorted(set(files))


def skipped(path, out_rel):
    if path == out_rel or SENSITIVE.search(path):
        return True
    parts = path.split("/")
    if any(p in SKIP_DIRS for p in parts[:-1]):
        return True
    return path.endswith(SKIP_SUFFIXES)


def read_text(root, path):
    full = os.path.join(root, *path.split("/"))
    try:
        if os.path.getsize(full) > MAX_BYTES:
            return None
        with open(full, "rb") as fh:
            data = fh.read()
    except OSError:
        return None
    if b"\0" in data[:8192]:
        return None
    return data.decode("utf-8", "replace")


def python_info(text):
    symbols, imports = [], []
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return symbols, imports
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            if not node.name.startswith("_"):
                symbols.append((node.name, node.lineno))
        elif isinstance(node, ast.Import):
            imports.extend((0, alias.name) for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            imports.append((node.level, node.module or ""))
            imports.extend((node.level, ((node.module or "") + "." + a.name).strip("."))
                           for a in node.names if a.name != "*")
    return symbols, imports


def pattern_info(text, key):
    symbols, imports = [], []
    for lineno, line in enumerate(text.splitlines(), 1):
        for pat in PATTERNS[key]:
            m = pat.match(line)
            if m:
                symbols.append((m.group(1), lineno))
                break
        if key == "js":
            imports.extend((0, m.group(1)) for m in JS_IMPORT.finditer(line))
    return symbols, imports


def resolve_python(path, level, module, known):
    if level:
        base = posixpath.dirname(path)
        for _ in range(level - 1):
            base = posixpath.dirname(base)
        parts = [p for p in [base] + module.split(".") if p]
    else:
        parts = module.split(".")
    stem = "/".join(parts)
    cands = [stem + ".py", stem + "/__init__.py"]
    if not level:
        cands += ["src/" + c for c in cands]
    for c in cands:
        c = posixpath.normpath(c)
        if c in known:
            return c
    return None


def resolve_js(path, spec, known):
    base = posixpath.normpath(posixpath.join(posixpath.dirname(path), spec))
    if base in known:
        return base
    stem = base
    for ext in (".js", ".jsx", ".mjs", ".cjs"):
        if stem.endswith(ext):
            stem = stem[: -len(ext)]
    for ext in JS_EXT:
        for c in (stem + ext, stem + "/index" + ext):
            if c in known:
                return c
    return None


def package_entries(root, known):
    entries = set()
    text = read_text(root, "package.json") if "package.json" in known else None
    if text:
        try:
            pkg = json.loads(text)
        except ValueError:
            pkg = {}
        vals = [pkg.get("main")]
        b = pkg.get("bin")
        vals += list(b.values()) if isinstance(b, dict) else [b]
        for v in vals:
            if isinstance(v, str):
                p = posixpath.normpath(v.lstrip("./") if v.startswith("./") else v)
                if p in known:
                    entries.add(p)
    return entries


def scan(root, out_rel):
    files = [f for f in git_files(root) if not skipped(f, out_rel)]
    known = set(files)
    info = {}
    for path in files:
        ext = posixpath.splitext(path)[1].lower()
        if ext not in LANG:
            continue
        text = read_text(root, path)
        if text is None:
            continue
        if ext == ".py":
            symbols, raw = python_info(text)
            deps = {resolve_python(path, lvl, mod, known) for lvl, mod in raw}
        elif ext in PATTERN_KEY:
            symbols, raw = pattern_info(text, PATTERN_KEY[ext])
            deps = {resolve_js(path, spec, known) for _, spec in raw} if ext in JS_EXT else set()
        else:
            symbols, deps = [], set()
        deps.discard(None)
        deps.discard(path)
        deps -= {d for d in deps if d.endswith("/__init__.py")
                 and any(x != d and x.startswith(d[: -len("__init__.py")]) for x in deps)}
        info[path] = {"lang": LANG[ext], "symbols": symbols, "deps": sorted(deps)}
    importers = {}
    for path, data in info.items():
        for d in data["deps"]:
            importers.setdefault(d, []).append(path)
    for v in importers.values():
        v.sort()
    entries = package_entries(root, known)
    for path in info:
        stem = posixpath.splitext(posixpath.basename(path))[0].lower()
        if stem in ENTRY_NAMES and path.count("/") <= 2:
            entries.add(path)
    return info, importers, sorted(e for e in entries if e in info), files


def is_test(path):
    parts = path.split("/")
    return any(p.lower() in TEST_DIRS for p in parts[:-1]) or bool(TEST_FILE.search(parts[-1]))


def top_dir(path):
    return path.split("/")[0] if "/" in path else "."


def file_lines(info, paths, cmd):
    lines = []
    for n, path in enumerate(sorted(paths)):
        if n >= MAX_FILES_PER_PAGE:
            lines.append("- (%d more; use `%s query`)" % (len(paths) - n, cmd))
            break
        names = [] if is_test(path) else [x for x, _ in info[path]["symbols"]]
        shown = ", ".join(names[:MAX_SYMBOLS])
        more = " (+%d more)" % (len(names) - MAX_SYMBOLS) if len(names) > MAX_SYMBOLS else ""
        lines.append("- `%s`%s" % (path, " — " + shown + more if shown else ""))
    return lines


def page_name(d):
    return ("root" if d == "." else re.sub(r"[^A-Za-z0-9._-]", "_", d)) + ".md"


def header(title, cmd):
    return [
        "# " + title,
        "",
        "%s (format %d) from git-tracked files. Do not edit by hand; regenerate with" % (MARKER, FORMAT),
        "`%s build`, check with `%s check`. Symbols are top-level definitions (approximate" % (cmd, cmd),
        "outside Python; none for tests); imports are local only.",
    ]


def render(info, importers, entries, cmd, out_rel, vault=None):
    """Return {relative path: text}: the map page, plus one page per directory if large."""
    by_dir = {}
    for path in info:
        by_dir.setdefault(top_dir(path), []).append(path)
    split = len(info) > SPLIT_ABOVE
    sub = posixpath.splitext(out_rel)[0]
    lines = header("Code map", cmd) + ["", "## Directories", ""]
    lines += ["| Directory | Source files | Languages |", "|---|---|---|"]
    for d in sorted(by_dir):
        langs = ", ".join(sorted({info[p]["lang"] for p in by_dir[d]}))
        cell = "`%s`" % d
        if split:
            cell = "[`%s`](%s/%s)" % (d, posixpath.basename(sub), page_name(d))
        lines.append("| %s | %d | %s |" % (cell, len(by_dir[d]), langs))
    if entries:
        lines += ["", "## Entry points", ""] + ["- `%s`" % e for e in entries]
    ranked = sorted((p for p in importers if p in info), key=lambda p: (-len(importers[p]), p))
    if ranked:
        lines += ["", "## Most imported", ""]
        lines += ["- `%s` — imported by %d files" % (p, len(importers[p])) for p in ranked[:TOP_IMPORTED]]
    if vault is not None:
        lines += ["", "## Vault", "",
                  "%d pages; %d broken links; %d orphan pages (no page links to them)."
                  % (len(vault["pages"]), len(vault["broken"]), len(vault["orphans"]))]
        lines += ["- broken: `%s:%d` → %s" % b for b in vault["broken"][:50]]
        lines += ["- orphan: `%s`" % o for o in vault["orphans"][:50]]
        rows = ["| Page | Title | Words | Linked from |", "|---|---|---|---|"]
        rows += ["| `%s` | %s | %d | %d |" % (pg, vault["meta"][pg][0], vault["meta"][pg][1],
                                              vault["inbound"][pg])
                 for pg in vault["pages"][:MAX_VAULT_ROWS]]
        if len(vault["pages"]) > MAX_VAULT_ROWS:
            rows.append("| (%d more) | | | |" % (len(vault["pages"]) - MAX_VAULT_ROWS))
        if len(vault["pages"]) > SPLIT_ABOVE:
            pages_name = sub + "/vault-pages.md"
            lines += ["", "Vault pages with titles: [vault pages](%s/vault-pages.md)."
                      % posixpath.basename(sub)]
            vault_page = header("Code map: vault pages", cmd) + [""] + rows
        else:
            lines += ["", "### Vault pages", ""] + rows
            pages_name = None
    pages = {}
    if vault is not None and pages_name:
        pages[pages_name] = "\n".join(vault_page) + "\n"
    if split:
        lines += ["", "Files and symbols per directory are on the linked pages."]
        for d in sorted(by_dir):
            body = header("Code map: `%s`" % d, cmd) + [""] + file_lines(info, by_dir[d], cmd)
            pages[sub + "/" + page_name(d)] = "\n".join(body) + "\n"
    else:
        for d in sorted(by_dir):
            lines += ["", "## `%s`" % d, ""] + file_lines(info, by_dir[d], cmd)
    pages[out_rel] = "\n".join(lines) + "\n"
    return pages


def generated_pages(root, out_rel):
    """Existing files this tool generated: the map page and its directory pages."""
    found = []
    sub = posixpath.splitext(out_rel)[0]
    folder = os.path.join(root, *sub.split("/"))
    if os.path.isdir(folder):
        for name in sorted(os.listdir(folder)):
            rel = sub + "/" + name
            if name.endswith(".md") and MARKER in (read_text(root, rel) or "")[:400]:
                found.append(rel)
    return found


def command_label():
    return "codemap.py"


# Vault links. Markdown pages under the vault folder are scanned outside fenced code blocks:
# [[wikilinks]] resolve by file name across the vault (a path-qualified link by path suffix,
# ties to the shallowest, then first path), [text](page.md) links resolve relative to the page,
# and inline code spans naming a tracked file are recorded as mentions of that file.
WIKILINK = re.compile(r"(?<!!)\[\[([^\]|#]+?)(?:\|[^\]]*|#[^\]]*)?\]\]")
MD_LINK = re.compile(r"(?<!!)\[[^\]]*\]\(<?([^)\s>]+)>?(?:\s+[^)]*)?\)")
CODE_SPAN = re.compile(r"`([^`\n]+)`")
FENCE = re.compile(r"^\s{0,3}(`{3,}|~{3,})")


def nfc(text):
    return unicodedata.normalize("NFC", text)


def prose_lines(text):
    fence = None
    for lineno, line in enumerate(text.splitlines(), 1):
        m = FENCE.match(line)
        if fence:
            if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) \
                    and not line.strip()[len(m.group(1)):].strip():
                fence = None
            continue
        if m:
            fence = m.group(1)
            continue
        yield lineno, line


def page_title(text, page):
    lines = text.splitlines()
    if lines and lines[0].strip() == "---":
        for line in lines[1:40]:
            if line.strip() == "---":
                break
            m = re.match(r"^title:\s*['\"]?(.+?)['\"]?\s*$", line)
            if m:
                return m.group(1)
    for _, line in prose_lines(text):
        m = re.match(r"^\s{0,3}#\s+(.+?)\s*#*\s*$", line)
        if m:
            return m.group(1)
    return posixpath.splitext(posixpath.basename(page))[0]


def scan_vault(root, vault, files, generated):
    if not vault:
        return None
    pages = sorted(f for f in files if f.startswith(vault + "/") and f.endswith(".md")
                   and f not in generated)
    by_name = {}
    for page in pages + sorted(generated):
        by_name.setdefault(nfc(posixpath.basename(page)).lower(), []).append(page)
    known = set(files)
    links, broken, mentions, meta = {p: set() for p in pages}, [], {}, {}
    for page in pages:
        text = read_text(root, page) or ""
        meta[page] = (page_title(text, page).replace("|", "/"), len(text.split()))
        for lineno, line in prose_lines(text):
            for target in WIKILINK.findall(line):
                target = nfc(target.strip())
                name = target if target.lower().endswith(".md") else target + ".md"
                cands = by_name.get(posixpath.basename(name).lower(), [])
                if "/" in name:
                    cands = [c for c in cands if nfc(c).lower().endswith("/" + name.lower())]
                cands.sort(key=lambda c: (c.count("/"), c))
                if cands:
                    links[page].add(cands[0])
                else:
                    broken.append((page, lineno, "[[%s]]" % target))
            for target in MD_LINK.findall(line):
                if re.match(r"^[a-z][a-z0-9+.-]*:|^#", target, re.I) or not target.endswith(".md"):
                    continue
                dest = posixpath.normpath(posixpath.join(posixpath.dirname(page), target))
                if dest in known or dest in generated:
                    links[page].add(dest)
                else:
                    broken.append((page, lineno, target))
            for span in CODE_SPAN.findall(line):
                ref = span.strip().split("::")[0].split(":")[0].lstrip("./")
                if ref in known and not ref.startswith(vault + "/"):
                    mentions.setdefault(ref, set()).add((page, lineno))
    inbound = {p: 0 for p in pages}
    for page, dests in links.items():
        for d in dests:
            if d in inbound and d != page:
                inbound[d] += 1
    orphans = [p for p in pages if not inbound[p] and posixpath.basename(p) != "index.md"]
    return {"dir": vault, "pages": pages, "broken": broken, "orphans": orphans,
            "mentions": mentions, "meta": meta, "inbound": inbound}


def detect_vault(root, files):
    """(vault dir or None, reason). Deterministic: the same files give the same answer."""
    md = [f for f in files if f.lower().endswith(".md")]
    dirs = sorted({posixpath.dirname(f) for f in md if posixpath.dirname(f)})
    prefixes = {"/".join(d.split("/")[:i]) for d in dirs
                for i in range(1, min(3, d.count("/") + 1) + 1)}
    tops = sorted(prefixes, key=lambda d: (d.count("/"), d))
    for d in tops:
        if os.path.isdir(os.path.join(root, *d.split("/"), ".obsidian")):
            return d, "has .obsidian/"
    for d in KNOWN_VAULTS:
        if any(f.startswith(d + "/") for f in md):
            return d, "known vault folder name"
    linked = []
    for f in md:
        text = read_text(root, f) or ""
        if any(WIKILINK.search(line) for _, line in prose_lines(text)):
            linked.append(f)
    if len(linked) >= 5:
        counts = {}
        for f in linked:
            parts = f.split("/")[:-1]
            for i in range(1, len(parts) + 1):
                counts["/".join(parts[:i])] = counts.get("/".join(parts[:i]), 0) + 1
        best = [d for d, c in counts.items() if c * 10 >= len(linked) * 8]
        if best:
            d = sorted(best, key=lambda d: (-d.count("/"), d))[0]
            return d, "holds most of the %d pages with [[wikilinks]]" % len(linked)
    return None, "no vault found"


def resolve_layout(root, files, vault_arg=None, out_arg=None):
    """(vault, map path, source). Config wins, then arguments, then detection."""
    cfg = {}
    text = read_text(root, CONFIG)
    if text:
        try:
            cfg = json.loads(text)
        except ValueError:
            cfg = {}
    if cfg and vault_arg is None and out_arg is None:
        return cfg.get("vault"), cfg.get("map") or NO_VAULT_MAP, CONFIG
    vault, reason = (vault_arg.strip("/"), "--vault") if vault_arg else detect_vault(root, files)
    if out_arg:
        return vault, out_arg, reason
    if not vault:
        return None, NO_VAULT_MAP, reason
    for name in ("map.md", "code-map.md", "code-map-generated.md"):
        rel = vault + "/" + name
        existing = read_text(root, rel)
        if existing is None or MARKER in existing[:400]:
            return vault, rel, reason
    return vault, vault + "/code-map-generated.md", reason


def changed_files(root, base):
    out = subprocess.run(["git", "-C", root, "diff", "--name-only", "--no-renames", base],
                         capture_output=True, check=True)
    return sorted({f for f in out.stdout.decode("utf-8", "replace").splitlines() if f})


def main(argv=None):
    ap = argparse.ArgumentParser(prog="codemap.py", description="Deterministic code map.")
    ap.add_argument("action", choices=["build", "check", "query", "mentions", "detect"])
    ap.add_argument("terms", nargs="*")
    ap.add_argument("--root", default=".")
    ap.add_argument("--out", help="map path (default: from %s, else detected)" % CONFIG)
    ap.add_argument("--vault", help="vault folder (default: from %s, else detected)" % CONFIG)
    ap.add_argument("--redetect", action="store_true", help="build: ignore and rewrite %s" % CONFIG)
    ap.add_argument("--base", help="mentions: use the files changed since this commit")
    args = ap.parse_args(argv)
    root = os.path.abspath(args.root)
    if not os.path.isdir(root):
        ap.error("no such directory: %s" % args.root)
    out_arg = None
    if args.out:
        out_arg = (os.path.relpath(os.path.abspath(args.out), root).replace(os.sep, "/")
                   if os.path.isabs(args.out) else args.out.replace("\\", "/"))
    tracked = git_files(root)
    if args.redetect and args.action == "build":
        tracked = [f for f in tracked if f != CONFIG]
        cfg_path = os.path.join(root, CONFIG)
        if os.path.exists(cfg_path):
            os.remove(cfg_path)
    vault_dir, out_rel, source = resolve_layout(root, tracked, args.vault, out_arg)
    if args.action == "detect":
        print("vault: %s (%s)" % (vault_dir or "none", source))
        print("map: %s" % out_rel)
        return 0
    info, importers, entries, files = scan(root, out_rel)
    cmd = command_label()
    planned = set(render(info, importers, entries, cmd, out_rel))
    existing = set(generated_pages(root, out_rel))
    vault = scan_vault(root, vault_dir, files, planned | existing | {out_rel})
    mentions = vault["mentions"] if vault else {}

    if args.action == "query":
        if len(args.terms) != 1:
            ap.error("query needs one TERM")
        term = args.terms[0].lower()
        hits = [(p, n, ln) for p, d in sorted(info.items()) for n, ln in d["symbols"]
                if term in n.lower()]
        paths = [p for p in sorted(info) if term in p.lower()]
        print("defined:" if hits else "defined: none")
        for p, n, ln in hits[:50]:
            print("  %s:%d %s" % (p, ln, n))
        print("paths:" if paths else "paths: none")
        for p in paths[:50]:
            users = importers.get(p, [])
            print("  %s (imported by %d)" % (p, len(users)))
            for u in users[:20]:
                print("    <- %s" % u)
            for page, ln in sorted(mentions.get(p, ()))[:20]:
                print("    mentioned in %s:%d" % (page, ln))
        return 0

    if args.action == "mentions":
        targets = list(args.terms)
        if args.base:
            try:
                targets += changed_files(root, args.base)
            except (OSError, subprocess.CalledProcessError):
                ap.error("cannot diff against %s" % args.base)
        found = 0
        for t in sorted(set(x.replace("\\", "/").lstrip("./") for x in targets)):
            for page, ln in sorted(mentions.get(t, ())):
                print("%s:%d mentions %s" % (page, ln, t))
                found += 1
        if not found:
            print("no vault page mentions these files")
        return 0

    pages = render(info, importers, entries, cmd, out_rel, vault)
    stale_extra = sorted(existing - set(pages))
    if args.action == "check":
        bad = []
        for rel, text in sorted(pages.items()):
            current = read_text(root, rel)
            if current is None or current.replace("\r\n", "\n") != text:
                bad.append(rel)
        bad += stale_extra
        for page, ln, target in (vault or {}).get("broken", [])[:20]:
            print("warning: broken link %s:%d -> %s" % (page, ln, target))
        if bad:
            print("stale: %s; run build" % ", ".join(bad))
            return 1
        print("current: %s" % out_rel)
        return 0
    for rel in stale_extra:
        os.remove(os.path.join(root, *rel.split("/")))
    if source != CONFIG and not args.out and not os.path.exists(os.path.join(root, CONFIG)):
        with open(os.path.join(root, CONFIG), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(json.dumps({"vault": vault_dir, "map": out_rel}, indent=2) + "\n")
        print("wrote %s (vault: %s, %s)" % (CONFIG, vault_dir or "none", source))
    for rel, text in sorted(pages.items()):
        path = os.path.join(root, *rel.split("/"))
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print("wrote %s (%d pages, %d source files)" % (out_rel, len(pages), len(info)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
