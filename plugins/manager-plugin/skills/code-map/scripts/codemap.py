# A `noqa` whose only code is E402 (an import after a sys.path setup): matched at the line's
# first `# noqa`, with no further code (letters then digits) after E402, whatever separates them.
NOQA_IMPORT = re.compile(r"#\s*noqa:\s*E402\b(?![^\n]*[A-Za-z]+\d)", re.I)
SUPPRESSIONS = (
    ("noqa", re.compile(r"#\s*noqa\b", re.I)),
    ("type: ignore", re.compile(r"#\s*type:\s*ignore\b")),
    ("eslint-disable", re.compile(r"\beslint-disable")),
    ("@ts-ignore", re.compile(r"@ts-(?:ignore|nocheck)\b")),
    ("nolint", re.compile(r"//\s*nolint\b")),
    ("pragma: no cover", re.compile(r"#\s*pragma:\s*no\s*cover\b")),
)
ASSERT_LINE = re.compile(r"assert|\bexpect\b", re.I)
TOML_HEADER = re.compile(r"^\s*\[\[?\s*([^\]]+?)\s*\]\]?\s*(?:#.*)?$")


def check_config(path):
    """The kind of lint, format, type-check, test or CI configuration a path is, or None."""
    name = posixpath.basename(path).lower()
    if path.startswith((".github/workflows/", ".circleci/")) or name in (
            ".gitlab-ci.yml", ".travis.yml", "azure-pipelines.yml", "jenkinsfile"):
        return "CI"
    if name.startswith(".pre-commit-config"):
        return "pre-commit"
    if name in (".flake8", "ruff.toml", ".ruff.toml", ".pylintrc", "pylintrc") or \
            name.startswith((".eslintrc", "eslint.config.", ".golangci", ".stylelintrc")):
        return "lint"
    if name in ("mypy.ini", ".mypy.ini", "pyrightconfig.json") or \
            (name.startswith("tsconfig") and name.endswith(".json")):
        return "type-check"
    if name.startswith((".prettierrc", "prettier.config.")):
        return "format"
    if name in ("setup.cfg", "tox.ini", "pytest.ini", ".coveragerc"):
        return "lint/test"
    return None


def tool_sections(text):
    """{name: text} of a pyproject.toml's [tool.*] tables."""
    found, name = {}, None
    for line in text.split("\n"):
        m = TOML_HEADER.match(line)
        if m:
            name = m.group(1) if m.group(1).startswith("tool.") else None
        if name:
            found[name] = found.get(name, "") + line + "\n"
    return found


def conditional(lines, n, start):
    """Whether the skip call at column `start` of lines[n] runs only under a condition: an `if`
    before it on its line, or the nearest line above with less indentation opens a branch."""
    line = lines[n]
    if IF_BEFORE.search(line[:start]):
        return True
    indent = len(line) - len(line.lstrip())
    for above in reversed(lines[:n]):
        if above.strip() and len(above) - len(above.lstrip()) < indent:
            return bool(CONDITION.match(above))
    return False


def guard_marks(text, test):
    """({skip label: lines}, {suppression label: lines}, assert/expect lines) of a file's text;
    skip markers marked test-only and assert lines are counted in test files only. Conditional
    skips (`skipIf`, `skipUnless`, `pytest.mark.skipif`, a skip call under a condition) and a
    `noqa` for E402 are not counted."""
    skips, quiet, asserts = {}, {}, 0
    lines = text.split("\n")
    for n, line in enumerate(lines):
        for label, rx, test_only, call in SKIP_MARKS:
            m = rx.search(line) if test or not test_only else None
            if m:
                if not (call and conditional(lines, n, m.start())):
                    skips[label] = skips.get(label, 0) + 1
                break
        for label, rx in SUPPRESSIONS:
            found = rx.search(line)
            if found:
                if not (label == "noqa" and NOQA_IMPORT.match(line, found.start())):
                    quiet[label] = quiet.get(label, 0) + 1
                break
        if test and ASSERT_LINE.search(line):
            asserts += 1
    return skips, quiet, asserts


def renamed_paths(root, base, head):
    """[(old path, new path)] of the renames git detects in `git diff base...head`."""
    items = git_lines(root, ["diff", "--name-status", "-z", "-M", "--relative",
                             "%s...%s" % (base, head)])
    found, n = [], 0
    while n < len(items):
        status = items[n]
        if status[:1] in ("R", "C"):
            if status[0] == "R":
                found.append((items[n + 1], items[n + 2]))
            n += 3
        else:
            n += 2
    return found


def weakened_lines(root, base, head, diff, out_rel):
    """The `possible weakened guards` section of `changed`, [] when nothing is found: test files
    deleted, renamed or moved; skip markers and suppressions added; net-removed assert/expect
    lines in a test file; edited lint, format, type-check, test or CI configuration. At most
    MAX_GUARD_LINES findings, then a count of the rest (all of them when one more would fit).
    Files that may hold secrets are never read."""
    entries = [e for e in diff if not is_map_page(e[1], out_rel)]
    moves = [(o, n) for o, n in renamed_paths(root, base, head)
             if not is_map_page(o, out_rel) and not is_map_page(n, out_rel)]
    gone, came = {o: n for o, n in moves}, {n: o for o, n in moves}
    old_blob = {path: old for _, path, old, _ in entries}
    found = []
    for o, n in moves:
        if is_test(o):
            where = ("moved and renamed" if posixpath.dirname(o) != posixpath.dirname(n) and
                     posixpath.basename(o) != posixpath.basename(n) else
                     "moved" if posixpath.dirname(o) != posixpath.dirname(n) else "renamed")
            found.append((0, o, "test file", "%s to %s%s" % (
                where, n, "" if is_test(n) else ", no longer named as a test")))
    sides = []  # (path, base blob, head blob, test file)
    for status, path, old, new in entries:
        kind = check_config(path)
        if kind:
            found.append((3, path, "check config", "%s config %s" % (
                kind, {"A": "added", "D": "deleted"}.get(status, "edited"))))
        if path in gone:
            continue
        if status == "D" and is_test(path):
            found.append((0, path, "test file", "deleted"))
            continue
        before = old_blob.get(came[path]) if path in came else old
        # test code: a test file in a language the map parses (no data files or fixtures)
        test = (is_test(path) or (path in came and is_test(came[path]))) and \
            posixpath.splitext(path)[1].lower() in LANG
        if not path.lower().endswith(PROSE) and not skipped(path, out_rel):
            sides.append((path, before, new, test))
    blobs = sorted({b for _, old, new, _ in sides for b in (old, new) if b})
    data = dict(zip(blobs, blob_bytes(root, blobs)))

    def text(blob):
        raw = data.get(blob) if blob else None
        if raw is None or len(raw) > MAX_BYTES or b"\0" in raw[:8192]:
            return ""
        return raw.replace(b"\r\n", b"\n").decode("utf-8", "replace")

    for path, old, new, test in sides:
        before, after = text(old), text(new)
        if posixpath.basename(path).lower() == "pyproject.toml":
            was, now = tool_sections(before), tool_sections(after)
            names = sorted(k for k in set(was) | set(now) if was.get(k) != now.get(k))
            if names:
                found.append((3, path, "check config", "%s edited" % ", ".join(
                    "[%s]" % k for k in names[:3]) + (" (+%d more)" % (len(names) - 3)
                                                      if len(names) > 3 else "")))
        (skips0, quiet0, asserts0), (skips1, quiet1, asserts1) = \
            guard_marks(before, test), guard_marks(after, test)
        for order, kind, was, now in ((1, "skip marker", skips0, skips1),
                                      (4, "suppression", quiet0, quiet1)):
            added = ["+%d %s" % (now[k] - was.get(k, 0), k) for k in sorted(now)
                     if now[k] > was.get(k, 0)]
            if added:
                found.append((order, path, kind, ", ".join(added)))
        if test and asserts0 > asserts1:
            found.append((2, path, "asserts", "%d fewer assert/expect line%s" % (
                asserts0 - asserts1, "" if asserts0 - asserts1 == 1 else "s")))
    if not found:
        return []
    found.sort()
    lines = ["possible weakened guards (approximate, never a filter):"]
    shown = found if len(found) <= MAX_GUARD_LINES + 1 else found[:MAX_GUARD_LINES]
    lines += ["  %s: %s: %s" % (kind, path, why) for _, path, kind, why in shown]
    if len(shown) < len(found):  # as the 60-line cap: a more-line only for two or more
        lines.append("  … %d more" % (len(found) - len(shown)))
    return lines


# `impact` and `query --budget`: run only when asked; nothing calls them by default.
WORD = re.compile(r"[A-Za-z_$][\w$]*")


def lang_family(lang):
    """Languages whose files can use each other's names: JavaScript and TypeScript, C and C++."""
    return {"TypeScript": "JavaScript", "C++": "C", "C/C++": "C"}.get(lang, lang)


def short_list(items, limit=IMPACT_NAMES):
    more = len(items) - limit
    return ", ".join(items[:limit]) + (" (+%d more)" % more if more > 0 else "")


def impact_lines(root, targets, depth, info, importers, out_rel):
    """The lines `impact` prints: per target file the map knows, its importers (import-based,
    each file once: direct, then each further level up to `depth`), the tests among them and
    those of its language family named after it (`test_<name>` ...), and per top-level
    definition the other source files of its language family whose text (Python: outside
    strings and comments) holds its name as a whole word, importers first (name-based: anything
    else of the same name counts too). Targets the map doesn't parse are named on one line at the
    end. `main` cuts it at MAX_CHANGED_LINES."""
    paths = sorted(set(targets))
    known = [p for p in paths if p in info]
    tests_by_stem = {}
    for p in sorted(info):
        stem = posixpath.splitext(posixpath.basename(p))[0]
        if is_test(p) and TEST_AFFIX.sub("", stem) != stem:  # a test_ / _test ... affix, not
            tests_by_stem.setdefault(TEST_AFFIX.sub("", stem).lower(), []).append(p)  # __init__
    wanted = {n.rstrip("?!") for p in known for n, _ in info[p]["symbols"][:MAX_CHANGED_NAMES]}
    users_of = {}
    for p in sorted(info) if wanted else ():
        text = read_text(root, p) or ""
        if info[p]["lang"] == "Python":  # outside strings and comments
            state, code = None, []
            for line in text.split("\n"):
                part, state = code_part(line, state)
                code.append(part)
            text = "\n".join(code)
        for word in wanted.intersection(WORD.findall(text)):
            users_of.setdefault(word, []).append(p)
    lines = ["impact: %d source file%s (imported by, depth, tests: import-based; tests by name, "
             "referenced: name-based, may include false matches)"
             % (len(known), "" if len(known) == 1 else "s")]
    for path in known:
        lines.append(path)
        found, seen = set(), {path}
        if info[path]["lang"] not in IMPORT_LANGS:
            lines.append("  imports: not parsed for %s" % info[path]["lang"])
        else:
            level = [path]
            for n in range(1, depth + 1):
                level = sorted({u for p in level for u in importers.get(p, ())} - seen)
                if not level:
                    break
                seen.update(level)
                found.update(u for u in level if is_test(u))
                rest = [u for u in level if not is_test(u)]
                if rest:
                    lines.append("  %s: %s" % ("imported by" if n == 1 else "depth %d" % n,
                                               short_list(rest)))
            if found:
                lines.append("  tests: %s" % short_list(sorted(found)))
        names, family = [n for n, _ in info[path]["symbols"]], lang_family(info[path]["lang"])
        stem = posixpath.splitext(posixpath.basename(path).lower())[0]
        named = [t for t in tests_by_stem.get(stem, []) if t not in found and t != path
                 and lang_family(info[t]["lang"]) == family]
        if named and not is_test(path):
            lines.append("  tests by name: %s" % short_list(named))
        for name in names[:MAX_CHANGED_NAMES]:
            users = [u for u in users_of.get(name.rstrip("?!"), [])
                     if u != path and lang_family(info[u]["lang"]) == family]
            users.sort(key=lambda u: u not in seen)  # importers first, each part sorted
            if users:
                lines.append("  referenced: %s: %s" % (name, short_list(users, MAX_SYMBOLS)))
        if len(names) > MAX_CHANGED_NAMES:
            lines.append("  (+%d more definitions)" % (len(names) - MAX_CHANGED_NAMES))
    other = [p for p in paths if p not in info and not is_map_page(p, out_rel)]
    if other:
        lines.append("not a source file in the map (other type, skipped or deleted): %s"
                     % short_list(other))
    return lines


def query_ranked(term, budget, info, importers, mentions, vault):
    """The lines of `query --budget`: the same items as `query` (50 per section at most),
    ranked (exact name or path matches first, then by how many files import the file or link to
    the page, then in `query`'s order) and kept, in rank order, while the output stays within
    about `budget` tokens (characters / CHARS_PER_TOKEN): one that doesn't fit is skipped, a
    later smaller one may still go in. The first ranked item is always kept; a cut ends with one
    line."""
    items = []  # (rank, section, lines)
    for p, d in sorted(info.items()):
        for n, ln in d["symbols"]:
            if term in n.lower():
                rank = (n.lower() != term, -len(importers.get(p, ())), 0, len(items))
                items.append((rank, 0, ["  %s:%d %s" % (p, ln, n)]))
    for p in sorted(info):
        if term in p.lower():
            users = importers.get(p, [])
            if info[p]["lang"] in IMPORT_LANGS:
                block = ["  %s (imported by %d local files)" % (p, len(users))]
            else:
                block = ["  %s (imports not parsed for %s)" % (p, info[p]["lang"])]
            block += ["    <- %s" % u for u in users[:20]]
            block += ["    mentioned in %s:%d" % m for m in mentions_of(mentions, p)[:20]]
            low = p.lower()
            exact = term in (low, posixpath.basename(low), posixpath.splitext(low)[0]) or \
                low.endswith("/" + term) or posixpath.splitext(low)[0].endswith("/" + term)
            items.append(((not exact, -len(users), 1, len(items)), 1, block))
    for pg in vault["pages"] if vault else ():
        title = vault["meta"][pg][0]
        low = pg.lower()
        if term in low or term in title.lower():
            exact = term in (low, title.lower(), posixpath.splitext(posixpath.basename(low))[0])
            block = ["  %s — %s (%d words, linked from %d)" % (pg, title, vault["meta"][pg][1],
                                                              vault["inbound"][pg])]
            items.append(((not exact, -vault["inbound"][pg], 2, len(items)), 2, block))
    heads = ["defined:", "paths:", "vault pages:"][:3 if vault else 2]
    present = {s for _, s, _ in items}
    shown, capped = {}, []  # `query` shows 50 items per section; the budget only cuts further
    for item in items:  # still in `query`'s order
        shown[item[1]] = shown.get(item[1], 0) + 1
        if shown[item[1]] <= 50:
            capped.append(item)
    over, items = len(items) - len(capped), capped
    size = sum(len(h) + 7 for s, h in enumerate(heads) if s not in present)  # "<head> none\n"
    ordered, total = sorted(items), len(items) + over
    full = size + sum(len(line) + 1 for _, _, block in ordered for line in block) + \
        sum(len(heads[s]) + 1 for s in present)
    limit = budget * CHARS_PER_TOKEN
    if full > limit or over:  # room for the line that says how many were cut
        limit -= len("… %d more (raise --budget)\n" % total)
    kept, count = {}, 0
    for _, s, block in ordered:  # in rank order; one that doesn't fit leaves room for the next
        cost = sum(len(line) + 1 for line in block) + (0 if s in kept else len(heads[s]) + 1)
        if kept and size + cost > limit:
            continue
        size += cost
        count += 1
        kept.setdefault(s, []).extend(block)
    lines = []
    for s, h in enumerate(heads):
        if s not in present:
            lines.append(h + " none")
        elif s in kept:
            lines += [h] + kept[s]
    if count < total:
        lines.append("… %d more (raise --budget)" % (total - count))
    return lines


# `calls`: run only when asked; nothing calls it by default. Live: it parses the working tree's
# Python files with `ast` on every run and writes nothing, so its answer depends on the running
# Python only for what it prints, never for a page.
CALLS_LIMIT = 40  # the lines of one section of one name; `--all`: no cap
CALLS_NAME = re.compile(r"^[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*$")
ATTR_CALLS = ("getattr", "setattr", "hasattr", "delattr")
CONSTRUCTORS = ("__init__", "__new__", "__post_init__")  # run by a call of their class
PY_SHEBANG = re.compile(r"^#![^\n]*\bpython")
CALLS_COVERAGE = ("coverage: static Python calls only; not seen: implicit calls (a constructor "
                  "running __init__, operators, `with`, `for`, protocol methods, a base class "
                  "or framework calling an override or a test, a decorator registering it), "
                  "dynamic calls (exec, getattr or lookups with computed names; a literal "
                  "getattr or lookup is listed and followed only as far as the name it is "
                  "assigned to), other languages, code outside the repository (frameworks or "
                  "tools calling it by name, other packages), untracked files, and tracked files "
                  "it skips or can't read (secrets, vendored folders, symlinks, over 512 KB, not "
                  "text: counted on the text line); calls through `from m import *`, imports it "
                  "cannot resolve, shadowed names and methods on objects of unknown type are "
                  "under possible; other names the function is bound to are under renamed; "
                  "before changing this function's signature or behaviour, also grep for the "
                  "name and those.")


def module_name(path):
    """`pkg.mod` of `pkg/mod.py`, `pkg` of `pkg/__init__.py`."""
    stem = posixpath.splitext(path)[0]
    if stem.endswith("/__init__") or stem == "__init__":
        stem = stem[: -len("__init__")].rstrip("/")
    return stem.replace("/", ".")


def stored_names(body):
    """The names a block assigns, binds as a loop, `with`, `except` or `case` target, or
    deletes, nested blocks included, the functions and classes it defines not."""
    found, todo = set(), list(body)
    while todo:
        node = todo.pop()
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Lambda)):
            continue
        if isinstance(node, ast.Name) and not isinstance(node.ctx, ast.Load):
            found.add(node.id)
        elif isinstance(node, ast.ExceptHandler) and node.name:
            found.add(node.name)
        elif type(node).__name__ in ("MatchAs", "MatchStar") and node.name:  # `case [x, *y]:`
            found.add(node.name)
        elif type(node).__name__ == "MatchMapping" and node.rest:
            found.add(node.rest)
        todo.extend(ast.iter_child_nodes(node))
    return found


def literal_lookup(node, name):
    """Whether a call or subscript holds the name as a whole string literal (`getattr(x,
    "f")`, `x.__dict__["f"]`, `attrgetter("f")(x)`)."""
    return isinstance(node, (ast.Call, ast.Subscript)) and any(
        isinstance(n, ast.Constant) and n.value == name for n in ast.walk(node))


class CallsFile:
    """One parsed Python file: its definitions by qualified name (`Class.method`, nested ones
    under their function), its top-level names and its import bindings (name -> (spec, the
    imported name)); spec: ("mod", level, dotted) or ("from", level, module, name); and its
    module-level assignments (`alias = core.helper`: name -> the expression assigned)."""

    def __init__(self, path, text, tree):
        self.path, self.lines, self.tree = path, text.split("\n"), tree
        self.defs, self.tops, self.bindings, self.assigns = {}, set(), {}, {}
        self.classes = {}  # qualified class name -> whether it has a base other than object
        self.decorated = set()  # qualified names of the decorated definitions
        self.nodes = {}  # qualified name -> its definition node (`explore` prints its range)
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                self.tops.add(node.name)
            elif isinstance(node, (ast.Assign, ast.AnnAssign)) and node.value is not None:
                for t in node.targets if isinstance(node, ast.Assign) else [node.target]:
                    if isinstance(t, ast.Name):
                        self.assigns[t.id] = node.value
        self.stores = stored_names(tree.body)  # names assigned at module level
        self.collect(tree, [])
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for a in node.names:
                    if a.asname:
                        self.bindings[a.asname] = (("mod", 0, a.name), a.name.split(".")[-1])
                    else:
                        top = a.name.split(".")[0]
                        self.bindings.setdefault(top, (("mod", 0, top), top))
            elif isinstance(node, ast.ImportFrom):
                for a in node.names:
                    if a.name != "*":
                        self.bindings[a.asname or a.name] = (
                            ("from", node.level or 0, node.module or "", a.name), a.name)

    def collect(self, node, stack):
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                qual = ".".join(stack + [child.name])
                self.defs.setdefault(qual, child.lineno)
                self.nodes.setdefault(qual, child)
                if child.decorator_list:
                    self.decorated.add(qual)
                if isinstance(child, ast.ClassDef):
                    self.classes[qual] = any(not (isinstance(b, ast.Name) and b.id == "object")
                                             for b in child.bases + child.keywords)
                self.collect(child, stack + [child.name])
            else:
                self.collect(child, stack)


class Calls:
    """The definitions, confident callers and possible references of one name (see
    `references/calls.md`)."""

    def __init__(self, parsed, known, target):
        self.parsed, self.known, self.target = parsed, known, target
        self.name = target.split(".")[-1]
        self.word = re.compile(r"(?<!\w)%s(?!\w)" % re.escape(self.name))
        self.definitions, self.callers, self.possible = set(), set(), set()
        self.keys = set()  # (path, qualified name) of the matching definitions
        for path, f in sorted(parsed.items()):
            for qual, line in f.defs.items():
                if qual.split(".")[-1] != self.name:
                    continue
                full = module_name(path) + "." + qual
                if target == self.name or full == target or full.endswith("." + target):
                    self.keys.add((path, qual))
                    self.definitions.add((path, line, qual))
        self.renamed = set()  # every other name the target is bound to, anywhere
        self.aliases = {path: set() for path in parsed}  # per file: such names bound in it
        self.find_aliases()
        self.module_aliases = set(self.renamed)  # `x.<alias>()` counts only for these
        self.failed = set()  # files too deeply nested to walk
        # the classes of matching `__init__`, `__new__`, `__post_init__`: their calls construct
        self.constructs = {(path, qual.rpartition(".")[0]) for path, qual in self.keys
                           if self.name in CONSTRUCTORS and "." in qual
                           and qual.rpartition(".")[0] in parsed[path].classes}
        # a dunder, a method (protocols such as `keys` too), a pytest name or conftest fixture
        self.implicit = (self.name.startswith("__") and self.name.endswith("__")) \
            or self.name.startswith(("test_", "pytest_")) or any(
                qual.rpartition(".")[0] in parsed[path].classes
                or posixpath.basename(path) == "conftest.py" for path, qual in self.keys)
        self.decorated = any(qual in parsed[path].decorated for path, qual in self.keys)
        for path, f in sorted(parsed.items()):
            self.file = f
            self.handled, self.scopes = set(), []
            try:
                self.walk(f.tree, [])
            except RecursionError:
                self.failed.add(path)

    def find_aliases(self):
        """The import bindings and module-level assignments that give the target another name:
        those that resolve to a matching definition, and those whose imported or assigned name
        is the target's or an alias found so far; and, the other way, the name such a binding of
        the target's or an alias's name imports or assigns (until no more are found)."""
        while True:
            before = len(self.renamed)
            for path, f in sorted(self.parsed.items()):
                self.file = f
                spelled = self.renamed | {self.name}
                found = [b for b, (spec, orig) in f.bindings.items() if orig in spelled
                         or self.canonical(self.spec(path, spec)) in self.keys]
                for a, value in f.assigns.items():
                    word = value.id if isinstance(value, ast.Name) else getattr(value, "attr", "")
                    if word in spelled or self.canonical(("sym", path, a)) in self.keys \
                            or any(literal_lookup(value, w) for w in spelled):
                        found.append(a)
                for b, (spec, orig) in f.bindings.items():  # `import x as <name>`: x too
                    if b in spelled and orig != self.name:
                        self.renamed.add(orig)
                for a, value in f.assigns.items():
                    if not isinstance(value, (ast.Name, ast.Attribute)):
                        continue
                    word = value.id if isinstance(value, ast.Name) else value.attr
                    if a in spelled and word != self.name:
                        self.renamed.add(word)
                for b in found:
                    if b != self.name:
                        self.renamed.add(b)
                        self.aliases[path].add(b)
            if len(self.renamed) == before:
                return

    def module(self, path, level, dotted):
        return resolve_python(path, level, dotted.strip("."), self.known) \
            if dotted.strip(".") or level else None

    def spec(self, path, spec):
        """A binding's spec as ("mod", path, level, dotted), ("sym", path, qual) or None."""
        if spec[0] == "mod":
            return ("mod", path, spec[1], spec[2])
        _, level, mod, name = spec
        sub = (mod + "." + name).strip(".")
        if self.module(path, level, sub):
            return ("mod", path, level, sub)
        where = self.module(path, level, mod)
        return ("sym", where, name) if where else None

    def attribute(self, ref, attr):
        if ref is None:
            return None
        if ref[0] == "sym":
            return ("sym", ref[1], ref[2] + "." + attr)
        _, path, level, dotted = ref
        sub = (dotted + "." + attr).strip(".")
        if self.module(path, level, sub):
            return ("mod", path, level, sub)
        where = self.module(path, level, dotted)
        return ("sym", where, attr) if where else ("mod", path, level, sub)

    def canonical(self, ref, depth=0):
        """(path, qualified name) a symbol reference ends at, following re-exports (`from x
        import f` in the file it names) up to 8 steps, or None."""
        if ref is None or ref[0] != "sym":
            return None
        path, qual = ref[1], ref[2]
        f = self.parsed.get(path)
        first, _, rest = qual.partition(".")
        if f is None or first in f.tops or depth >= 8 \
                or (first not in f.bindings and first not in f.assigns):
            return path, qual
        if first in f.bindings:
            found = self.spec(path, f.bindings[first][0])
        else:  # `alias = core.helper` at module level
            here, self.file = self.file, f
            found = self.resolve(f.assigns[first], [])
            self.file = here
        for part in rest.split(".") if rest else ():
            found = self.attribute(found, part)
        return self.canonical(found, depth + 1)

    def resolve(self, node, stack):
        """What an expression names, as for `spec`, or None when it can't tell."""
        f = self.file
        if isinstance(node, ast.Name):
            if node.id in ("self", "cls"):
                classes = [i for i, (kind, _) in enumerate(stack) if kind == "class"]
                if classes:
                    return ("sym", f.path, ".".join(n for _, n in stack[: classes[-1] + 1]))
            for i in range(len(stack), 0, -1):  # an enclosing function's own definitions
                if stack[i - 1][0] == "def":
                    qual = ".".join([n for _, n in stack[:i]] + [node.id])
                    if qual in f.defs:
                        return ("sym", f.path, qual)
            if node.id in f.bindings:
                return self.spec(f.path, f.bindings[node.id][0])
            if node.id in f.tops or node.id in f.assigns:
                return ("sym", f.path, node.id)
            return None
        if isinstance(node, ast.Attribute):
            return self.attribute(self.resolve(node.value, stack), node.attr)
        return None

    def ident(self, node):
        """The word naming the target in this Name or Attribute, an alias note, or None."""
        if isinstance(node, ast.Attribute):
            if node.attr == self.name:
                return ""
            return " (alias %s)" % node.attr if node.attr in self.module_aliases else None
        if isinstance(node, ast.Name):
            if node.id == self.name:
                return ""
            if node.id in self.aliases[self.file.path]:
                return " (alias %s)" % node.id
        return None

    def line_of(self, node, first=None, last=None):
        """The line of the word in node's lines, from the first; else node's first line."""
        first = first or node.lineno
        last = last or getattr(node, "end_lineno", None) or first
        for n in range(first, last + 1):
            if n - 1 < len(self.file.lines) and self.word.search(self.file.lines[n - 1]):
                return n
        return first

    def where(self, stack):
        return ".".join(n for _, n in stack) or MODULE_LEVEL

    def add(self, node, kind, line=None):
        self.possible.add((self.file.path, line or self.line_of(node), kind))

    def walk(self, node, stack):
        f = self.file
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            qual = ".".join([n for _, n in stack] + [node.name])
            if node.name == self.name and (f.path, qual) not in self.keys:
                self.add(node, "other definition", node.lineno)
            for d in node.decorator_list:
                if self.ident(d) is not None:
                    self.add(d, "decorator", self.end_line(d))
                    self.handled.add(id(d))
            inner = stack + [("class" if isinstance(node, ast.ClassDef) else "def", node.name)]
            if isinstance(node, ast.ClassDef):  # names its body assigns (seen by its methods
                self.scopes.append(stored_names(node.body))  # too here: on the safe side)
            else:  # its parameters and assigned names
                a = node.args
                params = a.posonlyargs if hasattr(a, "posonlyargs") else []
                params = params + a.args + a.kwonlyargs + [x for x in (a.vararg, a.kwarg) if x]
                self.scopes.append({x.arg for x in params} | stored_names(node.body))
            for field, value in ast.iter_fields(node):
                for child in value if isinstance(value, list) else [value]:
                    if isinstance(child, ast.AST):
                        self.walk(child, inner if field == "body" else stack)
            self.scopes.pop()
            return
        if isinstance(node, ast.Lambda):
            a = node.args
            params = (a.posonlyargs if hasattr(a, "posonlyargs") else []) + a.args + \
                a.kwonlyargs + [x for x in (a.vararg, a.kwarg) if x]
            self.scopes.append({x.arg for x in params})
            for child in ast.iter_child_nodes(node):
                self.walk(child, stack)
            self.scopes.pop()
            return
        if isinstance(node, ast.Call):
            func = node.func
            note = self.ident(func)
            if self.constructs and isinstance(func, (ast.Name, ast.Attribute)) \
                    and self.canonical(self.resolve(func, stack)) in self.constructs:
                self.add(func, "constructor call", self.end_line(func))
            if note is not None:
                self.handled.add(id(func))
                line = self.end_line(func)
                base = func
                while isinstance(base, ast.Attribute):
                    base = base.value
                shadowed = isinstance(base, ast.Name) and (base is func or base.id not in (
                    "self", "cls")) and (any(base.id in scope for scope in self.scopes)
                                         or base.id in f.stores)
                kind = "attribute call" if isinstance(func, ast.Attribute) else "call"
                if shadowed and self.resolve(func, stack) is not None:  # it may be another
                    self.add(func, kind + (note or " (shadowed)"), line)  # object here
                elif not shadowed and self.canonical(self.resolve(func, stack)) in self.keys:
                    self.callers.add((f.path, line, self.where(stack)))
                else:
                    self.add(func, kind + note, line)
            if isinstance(func, ast.Name) and func.id in ATTR_CALLS and len(node.args) >= 2:
                arg = node.args[1]
                if isinstance(arg, ast.Constant) and arg.value == self.name:
                    self.handled.add(id(arg))
                    self.add(arg, func.id)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)) and node.value is not None \
                and (self.ident(node.value) is not None  # `h = helper` in any scope
                     or literal_lookup(node.value, self.name)):  # `h = getattr(m, "helper")`
            named = self.ident(node.value) is not None
            for t in node.targets if isinstance(node, ast.Assign) else [node.target]:
                if isinstance(t, ast.Name) and t.id != self.name:
                    self.renamed.add(t.id)
                    self.aliases[f.path].add(t.id)
                    self.handled.add(id(t))  # listed once, as `renamed to`
                    if not named:
                        self.add(node.value, "renamed to %s" % t.id)
                    elif id(node.value) not in self.handled:  # followed: no `reference`
                        self.handled.add(id(node.value))
                        self.add(node.value, "renamed to %s" % t.id, self.end_line(node.value))
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            words = [w for a in node.names for w in a.name.split(".") + [a.asname]]
            if self.name in words + (getattr(node, "module", None) or "").split("."):
                self.add(node, "import")
            for alias in sorted(self.aliases[f.path].intersection(words)):
                self.add(node, "import (alias %s)" % alias, node.lineno)
        elif id(node) not in self.handled:
            note = self.ident(node) if isinstance(node, (ast.Name, ast.Attribute)) else None
            if note is not None:
                store = isinstance(node.ctx, ast.Store)
                kind = "assignment" if store else (
                    "attribute reference" if isinstance(node, ast.Attribute) else "reference")
                self.add(node, kind + note, self.end_line(node))
            elif isinstance(node, ast.Constant) and isinstance(node.value, str) \
                    and self.word.search(node.value):
                last = getattr(node, "end_lineno", None) or node.lineno
                lines = [n for n in range(node.lineno, last + 1) if n - 1 < len(f.lines)
                         and self.word.search(f.lines[n - 1])]
                for n in lines or [node.lineno]:
                    self.add(node, "string", n)
        for child in ast.iter_child_nodes(node):
            self.walk(child, stack)

    def end_line(self, node):
        """An Attribute's name is on its last line, a Name's on its only one."""
        if isinstance(node, ast.Attribute):
            return getattr(node, "end_lineno", None) or node.lineno
        return node.lineno


def calls_parse(root, files):
    """({path: CallsFile}, [not parsed: (path, why)]) of the map's Python files."""
    parsed, failed = {}, []
    for path in files:
        ext = posixpath.splitext(path)[1].lower()
        if ext not in (".py", ".pyw") and (ext or posixpath.basename(path).startswith(".")):
            continue
        text = read_text(root, path)
        if not ext:  # an extensionless script: Python when its first line says so
            if text is None or not PY_SHEBANG.match(text):
                continue
        if text is None:
            failed.append((path, "unreadable, too large or not text"))
            continue
        try:
            tree = ast.parse(text, filename=path)
        except SyntaxError as exc:
            nested = "too many nested" in str(exc.msg) or "too complex" in str(exc.msg)
            failed.append((path, "nested too deeply" if nested
                           else "syntax error, line %s" % exc.lineno))
            continue
        except RecursionError:
            failed.append((path, "nested too deeply"))
            continue
        except (ValueError, MemoryError):
            failed.append((path, "cannot be parsed by this Python"))
            continue
        try:
            parsed[path] = CallsFile(path, text, tree)
        except RecursionError:
            failed.append((path, "nested too deeply"))
    return parsed, failed


def text_line(found, total, shown, unparsed, capped, unread, other=0):
    """The `text:` line: the counts, each reason that applies, then `grep the rest`. It never
    says every occurrence is listed: a static scan can't know that. `other`: the occurrences in
    files not parsed as Python (config, notebooks, templates, other languages)."""
    line = "text: %d occurrence%s of %s, %d on lines listed above" % (
        total, "" if total == 1 else "s", found.name, shown)
    if found.renamed:
        line += "; renamed: %s" % ", ".join(sorted(found.renamed))
    stored = sum(1 for _, _, kind in found.possible
                 if kind.split(" (")[0] in ("reference", "attribute reference"))
    if stored:
        line += "; passed or stored at %d place%s, calls through %s not followed" % (
            stored, "" if stored == 1 else "s", "it" if stored == 1 else "them")
    if found.possible:
        line += "; %d possible" % len(found.possible)
    if found.implicit:
        line += "; called implicitly (operators, protocols, base classes, frameworks)"
    if found.decorated:
        line += "; decorated: may be registered and called through its decorator"
    if other:
        line += "; %d in files not parsed as Python" % other
    if unparsed:
        line += "; %d Python file%s not parsed" % (unparsed, "" if unparsed == 1 else "s")
    if unread:
        line += ("; %d tracked file%s not read (sensitive, vendored or skipped, symlinks, too "
                 "large or not text)" % (unread, "" if unread == 1 else "s"))
    if capped:
        line += "; cut (rerun with --all)"
    return line + "; grep the rest"


def calls_lines(root, targets, tracked, out_rel, everything=False, links=0):
    """The lines `calls` prints; see `references/calls.md`. `tracked`: the tracked files (no
    symlinks; `links`: how many were left out)."""
    files = [f for f in tracked if not skipped(f, out_rel)]
    parsed, failed = calls_parse(root, files)
    known = set(files)
    texts, unread = {}, links + sum(1 for f in tracked if skipped(f, out_rel)
                                    and not is_map_page(f, out_rel))  # secrets are never read
    for path in files:
        if not is_map_page(path, out_rel):
            text = read_text(root, path)
            if text is not None:
                texts[path] = text.split("\n")
            elif path not in dict(failed):  # a .py one is under `not parsed`
                unread += 1
    out, deep, bad = [], set(), dict(failed)  # bad: Python files, counted on their own
    for target in targets:
        found = Calls(parsed, known, target)
        deep |= found.failed
        listed, capped = set(), False
        out.append("calls %s" % target)
        code_first = sorted(found.possible, key=lambda i: (i[2] == "string", i))
        for head, items, show in (
                ("definitions", sorted(found.definitions), lambda i: "%s:%d %s" % i),
                ("callers", sorted(found.callers), lambda i: "%s:%d in %s" % i),
                ("possible", code_first, lambda i: "%s:%d %s" % i)):
            if not items:
                out.append("%s: none found" % head)
                continue
            out.append("%s:" % head)
            keep = items if everything or len(items) <= CALLS_LIMIT else items[:CALLS_LIMIT]
            for item in keep:
                out.append("  " + show(item))
                listed.add(item[:2])
            if len(keep) < len(items):
                capped = True
                out.append("  … %d more (rerun with --all)" % (len(items) - len(keep)))
        total = shown = other = 0
        for path in sorted(texts):
            python = path in parsed or path in bad
            for n, line in enumerate(texts[path], 1):
                hits = len(found.word.findall(line))
                total += hits
                if hits and (path, n) in listed:
                    shown += hits
                if not python:
                    other += hits
        out.append(text_line(found, total, shown, len(failed) + len(found.failed), capped,
                             unread, other))
    failed = failed + [(path, "nested too deeply") for path in sorted(deep)]
    if failed:
        out.append("not parsed: " + ", ".join("%s (%s)" % item for item in sorted(failed)))
    out.append(CALLS_COVERAGE)
    return out


# `explore`: the source of named definitions, live from the working tree (see
# `references/explore.md`). It reuses the `calls` parse and resolution and writes nothing.
EXPLORE_BUDGET = 8000  # printed characters by default (`--budget`: characters, not tokens)
EXPLORE_CALLERS = 10  # the resolved callers shown per name; `calls <name>` lists them all
EXPLORE_FILES = 3  # definitions in more than this many files: headers only
EXPLORE_APPROX = 300  # the most lines an approximate (not `ast`) range spans
EXPLORE_MEMBERS = 40  # the members listed for a class too big to show
EXPLORE_CUTS = 40  # the `cut:` lines listed, then one count
EXPLORE_NEAR = 5  # near matches for a name with no definition
KIND_WORD = re.compile(r"\b(function|class|interface|type|enum|const|let|var|func|struct|trait|"
                       r"fn|mod|module|def|protocol|actor|object|record)\b")
CONTROL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")  # a tab is kept: it is in the line format


def qualifies(target, path, qual):
    """Whether a name as `calls` takes it (`f`, `mod.f`, `Class.m`) names this definition."""
    full = module_name(path) + "." + qual
    return qual.split(".")[-1] == target.split(".")[-1] and (
        target == qual.split(".")[-1] or full == target or full.endswith("." + target))


def approx_end(lines, symbols, line, cap=EXPLORE_APPROX):
    """(end, capped) of a definition found by line pattern: the line before the next symbol of
    its file at the same or lower indentation, or the end of the file, trailing blank lines
    left out, at most `cap` lines."""
    def indent(n):
        text = lines[n - 1] if n - 1 < len(lines) else ""
        return len(text) - len(text.lstrip())
    end = len(lines)
    for _, other in sorted(symbols, key=lambda s: s[1]):
        if other > line and indent(other) <= indent(line):
            end = other - 1
            break
    while end > line and not lines[end - 1].strip():
        end -= 1
    return (line + cap - 1, True) if end - line + 1 > cap else (end, False)


def python_entry(path, f, qual):
    node = f.nodes[qual]
    start = min([d.lineno for d in node.decorator_list] + [node.lineno])
    parent = qual.rpartition(".")[0]
    kind = "class" if isinstance(node, ast.ClassDef) else (
        "method" if parent in f.classes else "function")
    if isinstance(node, ast.AsyncFunctionDef):
        kind = "async " + kind
    first = node.body[0].lineno if node.body else node.lineno
    members = []
    if isinstance(node, ast.ClassDef):
        for child in node.body:
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                members.append(python_entry(path, f, qual + "." + child.name))
    return {"path": path, "start": start, "end": node.end_lineno, "kind": kind, "name": qual,
            "lines": f.lines, "sig": max(node.lineno, first - 1), "members": members,
            "note": "", "lang": "Python", "body": first}


def pattern_entry(path, lang, lines, symbols, name, line, note=""):
    end, capped = approx_end(lines, symbols, line)
    m = KIND_WORD.search(lines[line - 1]) if line - 1 < len(lines) else None
    note = "end approximate%s%s" % (", cut at %d lines" % EXPLORE_APPROX if capped else "", note)
    kind = m.group(1) if m else "definition"
    kind = "function" if kind in ("def", "fn", "func") else kind
    return {"path": path, "start": line, "end": end, "kind": kind,
            "name": name, "lines": lines, "sig": line, "members": [], "note": " (%s)" % note,
            "lang": lang, "body": line + 1}


def explore_header(e):
    return CONTROL.sub("?", "%s:%d-%d %s %s%s" % (e["path"], e["start"], e["end"], e["kind"],
                                                  e["name"], e["note"])).replace("\t", "?")


def explore_source(e, first, last):
    """Lines first..last as `<number>\\t<line>` (`cat -n`, padded to the range's widest)."""
    width = len(str(e["end"]))
    return ["%*d\t%s" % (width, n, CONTROL.sub("?", e["lines"][n - 1].rstrip("\r")))
            for n in range(first, last + 1) if n - 1 < len(e["lines"])]


def explore_pointer(e, first):
    return "body not shown: read %s:%d-%d" % (CONTROL.sub("?", e["path"]), first, e["end"])


def chars(lines):
    return sum(len(line) + 1 for line in lines)


def explore_fit(e, left):
    """The lines one definition prints within `left` characters, or None (cut)."""
    full = [explore_header(e)] + explore_source(e, e["start"], e["end"])
    if chars(full) <= left:
        return full
    if e["members"]:  # a class: its signature, its members' ranges, a pointer
        lines = [explore_header(e)] + explore_source(e, e["start"], e["sig"])
        for m in e["members"][:EXPLORE_MEMBERS]:
            lines.append(CONTROL.sub("?", "  %d-%d %s %s" % (m["start"], m["end"], m["kind"],
                                                            m["name"])))
        if len(e["members"]) > EXPLORE_MEMBERS:
            lines.append("  … %d more members" % (len(e["members"]) - EXPLORE_MEMBERS))
        lines.append(explore_pointer(e, e["body"]))
        return lines if chars(lines) <= left else None
    lines = [explore_header(e)]  # a function: its first lines, at least the signature, then
    source = full[1:]  # a pointer to the rest
    keep = e["sig"] - e["start"] + 1
    used = chars(lines) + chars(source[:keep]) + len(explore_pointer(e, e["end"])) + 1
    if used > left:
        return None
    while keep < len(source) - 1 and used + len(source[keep]) + 1 <= left:
        used += len(source[keep]) + 1
        keep += 1
    return lines + source[:keep] + [explore_pointer(e, e["start"] + keep)]


def explore_lines(root, targets, tracked, out_rel, budget=EXPLORE_BUDGET):
    """The lines `explore` prints; see `references/explore.md`."""
    files = [f for f in tracked if not skipped(f, out_rel)]
    parsed, failed = calls_parse(root, files)
    known = set(files)
    others = []  # (path, language, lines, symbols, note) found by line pattern
    for path in files:
        ext = posixpath.splitext(path)[1].lower()
        if ext in PATTERN_KEY:
            text = read_text(root, path)
            if text is not None:
                symbols = pattern_info(text, PATTERN_KEY[ext])[0]
                others.append((path, LANG[ext], text.split("\n"), symbols, ""))
    for path, why in failed:
        text = read_text(root, path)
        if text is not None:
            others.append((path, "Python", text.split("\n"), python_info(text, True)[0],
                           "; not parsed: %s" % why))
    blocks = []  # per name: (lines before its definitions, definitions, headers only, after)
    for target in targets:
        found = Calls(parsed, known, target)
        entries = [python_entry(path, parsed[path], qual)
                   for path, _, qual in sorted(found.definitions)]
        for path, lang, lines, symbols, note in others:
            for name, line in symbols:
                if qualifies(target, path, name):
                    entries.append(pattern_entry(path, lang, lines, symbols, name, line, note))
        entries.sort(key=lambda e: (e["path"], e["start"]))
        if not entries:
            blocks.append((explore_near(target, parsed, others), [], False, []))
            continue
        paths = {e["path"] for e in entries}
        head = ["explore %s: %d definition%s in %d file%s" % (
            target, len(entries), "" if len(entries) == 1 else "s", len(paths),
            "" if len(paths) == 1 else "s")]
        many = len(paths) > EXPLORE_FILES
        if many:
            head[0] += ("; more than %d files: headers only, no source (qualify the name or "
                        "read a range)" % EXPLORE_FILES)
        after = []
        if any(e["lang"] == "Python" and not e["note"] for e in entries):
            callers = sorted(found.callers)
            after.append("callers:" if callers else
                         "callers: none resolved (not proof of none; run calls %s)" % target)
            after += [CONTROL.sub("?", "  %s:%d in %s" % c) for c in callers[:EXPLORE_CALLERS]]
            if len(callers) > EXPLORE_CALLERS:
                after.append("  more: %d; run calls %s" % (len(callers) - EXPLORE_CALLERS,
                                                          target))
            after.append("possible: %d (calls %s lists them)" % (len(found.possible), target))
        for lang in sorted({e["lang"] for e in entries if e["lang"] != "Python"}):
            after.append("callers: not resolved for %s; grep -n -w %s" % (lang, target.split(
                ".")[-1]))
        if any(e["note"] and e["lang"] == "Python" for e in entries):
            after.append("callers: not resolved in Python files not parsed; grep -n -w %s"
                         % target.split(".")[-1])
        blocks.append((head, entries, many, after))
    left = budget - sum(chars(head) + chars(after) for head, _, _, after in blocks)
    out, cut = [], []
    for head, entries, many, after in blocks:
        out += head
        for e in entries:
            lines = [explore_header(e)] if many else explore_fit(e, left)
            if lines is None or chars(lines) > left:
                cut.append("cut: " + explore_header(e))
                continue
            out += lines
            left -= chars(lines)
        out += after
    if len(cut) > EXPLORE_CUTS:
        cut[EXPLORE_CUTS:] = ["cut: %d more definitions not listed; qualify the name" % (
            len(cut) - EXPLORE_CUTS)]
    if cut:
        out.append("over the budget of %d characters (--budget):" % budget)
    return out + cut


def explore_near(target, parsed, others):
    """No definition: at most EXPLORE_NEAR `query`-style near matches (`file:line name`)."""
    term = target.split(".")[-1].lower()
    defs = sorted({(path, line, qual) for path, f in parsed.items()
                   for qual, line in f.defs.items()} | {
        (path, line, name) for path, _, _, symbols, _ in others for name, line in symbols})
    near = [d for d in defs if term in d[2].split(".")[-1].lower()]
    if not near:
        close = set(difflib.get_close_matches(term, {d[2].split(".")[-1].lower() for d in defs},
                                              EXPLORE_NEAR, 0.75))
        near = [d for d in defs if d[2].split(".")[-1].lower() in close]
    lines = ["explore %s: no definition named %s; near matches:%s" % (
        target, target, "" if near else " none found")]
    return lines + [CONTROL.sub("?", "  %s:%d %s" % d) for d in near[:EXPLORE_NEAR]]


