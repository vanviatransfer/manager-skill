# [[wikilinks]] resolve by file name across the vault (a path-qualified link by path suffix,
# ties to the shallowest, then first path), [text](page.md) links resolve relative to the page,
# and inline code spans naming a tracked file are recorded as mentions of that file.
# Dead sources (`check` only, beside the broken links): a cited path that no longer exists. A
# link to a non-page file counts as cited, and so does a code span with a `/` that ends in `/` or
# in a file extension, but only when the path's first part is an entry of the repository root or
# a folder name anywhere in the tracked tree (else it likely names another repository's file);
# skipped: fenced code blocks, placeholders (`<`, `>`, `*`, `{`, `$`, `...`, `path/to`, a part
# named foo, bar, baz or holding "example"). A cited path is alive when it is on disk from the
# root, or a tracked path is it or ends with "/" + it (`scripts/x.py`), or, for a folder, holds it.
WIKILINK = re.compile(r"\[\[([^\]|#\\]+?)(?:\\?\|[^\]]*|#[^\]]*)?\]\]")
MD_LINK = re.compile(r"(?<!!)\[[^\]]*\]\(\s*(?:<([^<>\n]+)>|([^)\s]+))(?:\s+[^)]*)?\)")
CODE_SPAN = re.compile(r"`([^`\n]+)`")
FENCE = re.compile(r"^\s{0,3}(`{3,}|~{3,})")


def nfc(text):
    return unicodedata.normalize("NFC", text)


def prose_lines(text):
    fence = None
    for lineno, line in enumerate(text.split("\n"), 1):
        m = FENCE.match(line)
        if fence:
            if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) \
                    and not line.strip()[len(m.group(1)):].strip():
                fence = None
            continue
        if m:
            fence = m.group(1)
            continue
        yield lineno, line


def page_title(text, page):
    lines = text.split("\n")
    if lines and lines[0].strip() == "---":
        for line in lines[1:40]:
            if line.strip() == "---":
                break
            m = re.match(r"^title:\s*['\"]?(.+?)['\"]?\s*$", line)
            if m:
                return m.group(1)
    for _, line in prose_lines(text):
        m = re.match(r"^\s{0,3}#\s+(.+?)\s*#*\s*$", line)
        if m:
            return m.group(1)
    return posixpath.splitext(posixpath.basename(page))[0]


PATH_LIKE = re.compile(r"^[\w.@-]+(?:/[\w.@-]+)*/?$")
CITED_FILE = re.compile(r"/(?:$|[^/]*\.[A-Za-z]\w*$)")


def placeholder_path(ref):
    if re.search(r"[<>*{}$]|\.\.\.|(?:^|/)path/to/", ref):
        return True
    parts = [posixpath.splitext(part)[0].lower() for part in ref.split("/") if part]
    return any(part in ("foo", "bar", "baz") or "example" in part for part in parts)


def dead_sources(root, cited, known):
    """[(page, line, path)] of the cited paths that no longer exist (see the rule above)."""
    tracked = ["/" + f for f in sorted(known)]
    folders = {f.split("/")[0] for f in known}  # the root's entries, then every folder name
    folders.update(part for f in known for part in f.split("/")[:-1])
    dead = []
    for page, lineno, ref in cited:
        if ref.split("/")[0] not in folders:
            continue  # likely another repository's file
        if placeholder_path(ref) or os.path.lexists(os.path.join(root, *ref.split("/"))):
            continue
        if any(("/" + ref) in f if ref.endswith("/") else f.endswith("/" + ref)
               for f in tracked):
            continue  # a tracked path is it, or ends with it
        dead.append((page, lineno, ref))
    return dead


def in_vault(path, vault):
    return vault == "." or path.startswith(vault + "/")


def is_page(path, vault):
    return in_vault(path, vault) and path.lower().endswith(".md")


def strip_dot_slash(ref):
    while ref.startswith("./"):
        ref = ref[2:]
    return ref


def scan_vault(root, vault, files, generated):
    if not vault:
        return None
    pages = sorted(f for f in files if in_vault(f, vault) and f.lower().endswith(".md")
                   and f not in generated and not skipped(f, ""))
    known = set(files)
    by_name = {}
    for f in sorted(known | set(generated)):
        if in_vault(f, vault):
            by_name.setdefault(nfc(posixpath.basename(f)).lower(), []).append(f)
    links, broken, mentions, meta, cited = {p: set() for p in pages}, [], {}, {}, []
    for page in pages:
        text = read_text(root, page) or ""
        meta[page] = (page_title(text, page).replace("|", "/")[:60], len(text.split()))
        for lineno, full_line in prose_lines(text):
            line = CODE_SPAN.sub(" ", full_line)
            for target in WIKILINK.findall(line):
                target = nfc(target.strip())
                cands = []
                for name in (target + ".md", target):  # "Release 1.0" is a page, "a.png" a file
                    found = by_name.get(posixpath.basename(name).lower(), [])
                    if "/" in name:
                        found = [c for c in found
                                 if ("/" + nfc(c).lower()).endswith("/" + name.lower())]
                    if found:
                        cands = found
                        break
                cands.sort(key=lambda c: (c.count("/"), c))
                if cands:
                    links[page].add(cands[0])
                else:
                    broken.append((page, lineno, "[[%s]]" % target))
            for angled, bare in MD_LINK.findall(line):
                target = unquote((angled or bare).split("#")[0])
                if not target or re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I):
                    continue
                dest = posixpath.normpath(posixpath.join(posixpath.dirname(page), target))
                if not target.lower().endswith(".md"):
                    if not dest.startswith("../") and not is_page(dest, vault):
                        mentions.setdefault(dest, set()).add((page, lineno))
                        cited.append((page, lineno, dest))
                    continue
                rooted = posixpath.normpath(posixpath.join("" if vault == "." else vault,
                                                           target.lstrip("/")))
                if dest in known or dest in generated:
                    links[page].add(dest)
                elif rooted in known or rooted in generated:
                    links[page].add(rooted)
                else:
                    broken.append((page, lineno, target))
            for span in CODE_SPAN.findall(full_line):
                ref = strip_dot_slash(span.strip().split("::")[0].split(":")[0])
                if PATH_LIKE.match(ref) and ("/" in ref or "." in ref) and not is_page(ref, vault):
                    mentions.setdefault(ref, set()).add((page, lineno))
                    if CITED_FILE.search(ref) and not ref.startswith("/"):
                        cited.append((page, lineno, ref))
    inbound = {p: 0 for p in pages}
    for page, dests in links.items():
        for d in dests:
            if d in inbound and d != page:
                inbound[d] += 1
    entry = {"index.md", "readme.md", "home.md", "_index.md"}
    orphans = [p for p in pages if not inbound[p] and posixpath.basename(p).lower() not in entry]
    return {"dir": vault, "pages": pages, "broken": broken, "orphans": orphans,
            "mentions": mentions, "meta": meta, "inbound": inbound,
            "dead": lambda: dead_sources(root, cited, known | set(generated))}


def mentions_of(mentions, path):
    """Vault references to a path: the path itself, or a directory that contains it."""
    found = set(mentions.get(path, ()))
    for ref, where in mentions.items():
        if ref.endswith("/") and path.startswith(ref):
            found |= where
        elif ref != path and path.startswith(ref + "/"):
            found |= where
    return sorted(found)


def wikilinked(root, f):
    text = read_text(root, f) or ""
    return any(WIKILINK.search(CODE_SPAN.sub(" ", line)) for _, line in prose_lines(text))


def detect_vault(root, files):
    """(vault dir or None, reason). Deterministic: the same files give the same answer."""
    md = [f for f in files if f.lower().endswith(".md") and not skipped(f, "")]
    if not md:
        return None, "no markdown files"
    if os.path.isdir(os.path.join(root, ".obsidian")):
        return ".", "has .obsidian/ at the root"
    dirs = sorted({posixpath.dirname(f) for f in md if posixpath.dirname(f)})
    prefixes = {"/".join(d.split("/")[:i]) for d in dirs
                for i in range(1, min(3, d.count("/") + 1) + 1)}
    for d in sorted(prefixes, key=lambda d: (d.count("/"), d)):
        if os.path.isdir(os.path.join(root, *d.split("/"), ".obsidian")):
            return d, "has .obsidian/"
    for d in KNOWN_VAULTS:
        inside = [f for f in md if f.startswith(d + "/")]
        if d in STRONG_VAULT_NAMES and inside:
            return d, "known vault folder name"
        if len(inside) >= 3 and any(wikilinked(root, f) for f in inside):
            return d, "known folder name with [[wikilinks]]"
    linked = [f for f in md if wikilinked(root, f)]
    if len(linked) >= 5:
        counts = {}
        for f in linked:
            parts = f.split("/")[:-1]
            for i in range(1, len(parts) + 1):
                counts["/".join(parts[:i])] = counts.get("/".join(parts[:i]), 0) + 1
        best = [d for d, c in counts.items() if c * 10 >= len(linked) * 8]
        if best:
            d = sorted(best, key=lambda d: (-d.count("/"), d))[0]
            return d, "holds most of the %d pages with [[wikilinks]]" % len(linked)
    return None, "no vault found"


class LayoutError(Exception):
    pass


def safe_rel(value, what):
    if value is None:
        return None
    if not isinstance(value, str):
        raise LayoutError("%s in %s must be a string" % (what, CONFIG))
    value = value.replace("\\", "/").strip()
    norm = posixpath.normpath(value) if value else ""
    if not norm or norm.startswith("/") or re.match(r"^[A-Za-z]:", norm) or \
            norm == ".." or norm.startswith("../"):
        if norm != ".":
            raise LayoutError("%s must be a path inside the repository: %r" % (what, value))
    return norm


def foreign_in_map_dir(root, out):
    """Files in the map's page folder that this tool didn't write."""
    folder = os.path.join(root, *posixpath.splitext(out)[0].split("/"))
    if is_link(folder):
        return [posixpath.splitext(out)[0] + " (a symlink)"]
    if not os.path.isdir(folder):
        return []
    sub = posixpath.splitext(out)[0]
    return [sub + "/" + n for n in sorted(os.listdir(folder))
            if not (n.endswith(".md") and is_generated(read_text(root, sub + "/" + n)))]


def is_generated(text):
    lines = (text or "").splitlines()
    return len(lines) > 2 and lines[2].startswith(MARKER + " (format")


def link_in_path(root, rel):
    """True if the path, a folder on the way to it inside the repo, or (for a map) its page
    folder is a symlink."""
    parts = rel.split("/")
    if any(is_link(os.path.join(root, *parts[:i])) for i in range(1, len(parts) + 1)):
        return True
    return rel.lower().endswith(".md") and is_link(
        os.path.join(root, *posixpath.splitext(rel)[0].split("/")))


def check_map_path(root, out):
    if not out.lower().endswith(".md"):
        raise LayoutError("map must be a .md file: %r" % out)
    full = os.path.join(root, *out.split("/"))
    if link_in_path(root, out):
        raise LayoutError("map %r is, or lies under, a symlink" % out)
    foreign = foreign_in_map_dir(root, out)
    if foreign:
        raise LayoutError("the map's page folder holds files this tool didn't write: %s"
                          % ", ".join(foreign))
    existing = read_text(root, out)
    if os.path.isdir(full) or (os.path.lexists(full) and not is_generated(existing)):
        raise LayoutError("map %r is an existing file this tool didn't write" % out)


def read_config(root):
    if is_link(os.path.join(root, CONFIG)):
        raise LayoutError("%s is a symlink; replace it with a plain file" % CONFIG)
    text = read_text(root, CONFIG)
    if not text:
        return None
    try:
        cfg = json.loads(text)
    except ValueError:
        raise LayoutError("%s is not valid JSON" % CONFIG)
    if not isinstance(cfg, dict):
        raise LayoutError("%s must hold an object" % CONFIG)
    return cfg


def default_map(root, vault):
    if not vault:
        names = (NO_VAULT_MAP, "docs/code-map-generated.md")
    else:
        base = "" if vault == "." else vault + "/"
        names = tuple(base + n for n in ("map.md", "code-map.md", "code-map-generated.md"))
    for rel in names:
        existing = read_text(root, rel)
        free = existing is None and not os.path.lexists(os.path.join(root, *rel.split("/")))
        if (free or is_generated(existing)) and not foreign_in_map_dir(root, rel) \
                and not link_in_path(root, rel):
            return rel
    raise LayoutError("no free map location: %s each hold a file this tool didn't write, a "
                      "symlink, or hand-written pages; set \"map\" in %s"
                      % (", ".join(names), CONFIG))


def resolve_layout(root, files, vault_arg=None, out_arg=None, use_config=True):
    """(vault, map path, source). Config wins, then arguments, then detection."""
    cfg = read_config(root) if use_config else None
    if cfg and vault_arg is None and out_arg is None:
        vault = safe_rel(cfg.get("vault"), "vault")
        out = safe_rel(cfg.get("map"), "map") or default_map(root, vault)
        check_map_path(root, out)
        return vault, out, CONFIG
    if vault_arg:
        vault, reason = safe_rel(vault_arg, "--vault"), "--vault"
    else:
        vault, reason = detect_vault(root, files)
    return vault, out_arg or default_map(root, vault), reason


def changed_files(root, base):
    out = subprocess.run(["git", "-C", root, "diff", "--name-only", "--no-renames", base],
                         capture_output=True, check=True)
    return sorted({f for f in out.stdout.decode("utf-8", "replace").splitlines() if f})


def is_map_page(path, out_rel):
    return path == out_rel or path.startswith(posixpath.splitext(out_rel)[0] + "/")


def is_content_input(path, vault):
    """A tracked file whose content (not only its path) can change the map."""
    return (posixpath.splitext(path)[1].lower() in LANG or path == "package.json"
            or bool(vault and is_page(path, vault)))


def git_lines(root, args, nul=True):
    out = subprocess.run(["git", "-C", root] + args, capture_output=True, check=True)
    text = out.stdout.decode("utf-8", "replace")
    return [x for x in text.split("\0" if nul else "\n") if x]


def readable_file(root, path):
    return not link_in_path(root, path) and os.path.isfile(os.path.join(root, *path.split("/")))


def arg_batches(paths, limit=24000):
    """The paths in runs whose total length stays under a command-line limit (Windows: 32,767)."""
    batch, size = [], 0
    for p in paths:
        if batch and size + len(p) + 3 > limit:
            yield batch
            batch, size = [], 0
        batch.append(p)
        size += len(p) + 3
    if batch:
        yield batch


def blob_bytes(root, ids):
    """The bytes of each blob, in the order asked, from one `git cat-file --batch`."""
    out = subprocess.run(["git", "-C", root, "cat-file", "--batch"], capture_output=True,
                         check=True, input="".join(blob + "\n" for blob in ids).encode())
    data, pos, found = out.stdout, 0, []
    for _ in ids:
        end = data.index(b"\n", pos)
        size = int(data[pos:end].split()[2])
        found.append(data[end + 1:end + 1 + size])
        pos = end + 2 + size
    return found


def file_hashes(root, paths, filters=False):
    """The blob id of each file's working-tree bytes, in the order asked: of the raw bytes, or
    with `filters` of what `git add` would store (its clean filter, `ident`, line-ending and
    `working-tree-encoding` conversions). git writes no object for either."""
    kind = [] if filters else ["--no-filters"]
    found = []
    for batch in arg_batches(paths):
        out = subprocess.run(["git", "-C", root, "hash-object"] + kind + ["--"] + batch,
                             capture_output=True, check=True)
        got = out.stdout.decode().split()
        if len(got) != len(batch):
            raise GitError("git hash-object returned %d hashes for %d files"
                           % (len(got), len(batch)))
        found += got
    return found


def worktree_differs(root, paths, blobs):
    """The paths whose working-tree bytes, as the scan would read them, aren't the indexed blob.

    Raw bytes (git hash-object --no-filters), so a clean filter, assume-unchanged or
    skip-worktree can't hide a change. Paths go to git as arguments after `--`, never as lines
    git would unquote. A file whose raw bytes differ is compared with its blob after the scan's
    own CRLF-to-LF step, so a core.autocrlf checkout isn't a change. Missing paths and those
    that aren't readable regular files are left to the caller (see readable_file)."""
    present = [p for p in paths if p in blobs and readable_file(root, p)]
    differs = [p for p, b in zip(present, file_hashes(root, present)) if b != blobs[p]]
    if not differs:
        return []
    changed = []
    for p, blob in zip(differs, blob_bytes(root, [blobs[p] for p in differs])):
        with open(os.path.join(root, *p.split("/")), "rb") as fh:
            if fh.read().replace(b"\r\n", b"\n") != blob.replace(b"\r\n", b"\n"):
                changed.append(p)
    return changed


# `changed`: pointers for a review of `git diff base...head`. Definitions are read from the two
# commits; importers, tests and vault mentions from the scan of the working tree.
TEST_AFFIX = re.compile(r"^test_|(?:_test|_spec|\.test|\.spec|Tests?)$")


def diff_entries(root, base, head):
    """[(status letter, path, base blob, head blob)] of `git diff base...head`: the paths under
    root, relative to it; a blob is None on a side where the path is no regular file."""
    items = git_lines(root, ["diff", "--raw", "-z", "--no-renames", "--relative", "--no-abbrev",
                             "%s...%s" % (base, head)])
    found = []
    for meta, path in zip(items[0::2], items[1::2]):
        old_mode, new_mode, old, new, status = meta[1:].split()
        found.append((status[0], path, old if old_mode.startswith("100") else None,
                      new if new_mode.startswith("100") else None))
    return found


def definitions(path, data):
    """{name: text} of the top-level definitions in a source file's bytes (None: none), to compare
    two versions of it. One runs from the comment and decorator lines right above it up to the
    next one's, so a change between two counts for the first; Python's private ones are included.
    Under MODULE_LEVEL: the text above the first one (all of it when there is none), without its
    empty lines.
    """
    if data is None or len(data) > MAX_BYTES or b"\0" in data[:8192]:
        return {}
    text = data.replace(b"\r\n", b"\n").decode("utf-8", "replace")
    key = PATTERN_KEY.get(posixpath.splitext(path)[1].lower())
    symbols = pattern_info(text, key)[0] if key else python_info(text, private=True)[0]
    lines, starts = text.split("\n"), []
    for _, start in symbols:
        while start > 1 and lines[start - 2].lstrip()[:1] in ("@", "#", "/", "*"):
            start -= 1
        starts.append(start)
    starts.append(len(lines) + 1)
    found = {MODULE_LEVEL: "\n".join(line for line in lines[:starts[0] - 1] if line.strip())}
    for (name, _), start, end in zip(symbols, starts, starts[1:]):
        found[name] = found.get(name, "") + "\n".join(lines[start - 1:end - 1]).rstrip() + "\n"
    return found


def changed_lines(root, diff, head, info, importers, mentions, out_rel):
    """The lines `changed` prints, before the cap: per file of `diff`, the `diff_entries` of
    `git diff base...head` (map pages left out), its status and path, then what there is of: the
    top-level definitions whose text differs between the two commits (first MODULE_LEVEL, when
    the text above them differs), the files that import it (a deleted file: `scan` was given
    its path), its tests (they import it, or a source file gives them its name) and the vault
    lines that mention it. Files that may hold secrets are never read."""
    def parsed(path):
        ext = posixpath.splitext(path)[1].lower()
        return (ext == ".py" or ext in PATTERN_KEY) and not skipped(path, out_rel)

    entries = [e for e in diff if not is_map_page(e[1], out_rel)]
    blobs = sorted({blob for _, path, old, new in entries if parsed(path)
                    for blob in (old, new) if blob})
    data = dict(zip(blobs, blob_bytes(root, blobs)))
    tests = {}
    for path in sorted(info):
        if is_test(path):
            stem = posixpath.splitext(posixpath.basename(path))[0]
            tests.setdefault(TEST_AFFIX.sub("", stem).lower(), []).append(path)
    lines = ["changed: %d file%s" % (len(entries), "" if len(entries) == 1 else "s")]
    if len(set(git_lines(root, ["rev-parse", "HEAD", head + "^{commit}"], nul=False))) > 1:
        lines.append("note: HEAD is not %s; importers, tests and vault pages are the working "
                     "tree's" % head)
    for status, path, old, new in entries:
        lines.append("%s %s" % (status, path))
        before = definitions(path, data.get(old) if parsed(path) else None)
        after = definitions(path, data.get(new) if parsed(path) else None)
        above = (before.pop(MODULE_LEVEL, None), after.pop(MODULE_LEVEL, None))
        new_mark, gone_mark = (" (new)", " (removed)") if status == "M" else ("", "")
        names = [MODULE_LEVEL] if None not in above and above[0] != above[1] else []
        names += [name + ("" if name in before else new_mark) for name in after
                  if after[name] != before.get(name)]
        names += [name + gone_mark for name in before if name not in after]
        users = importers.get(path, [])
        stem, ext = posixpath.splitext(posixpath.basename(path).lower())
        named = tests.get(stem, []) if ext in LANG and not is_test(path) else []
        for label, items in (
                ("definitions", names),
                ("imported by", [user for user in users if not is_test(user)]),
                ("tests", sorted(set(named) | {user for user in users if is_test(user)})),
                ("vault", ["%s:%d" % where for where in mentions_of(mentions, path)])):
            if items:
                more = len(items) - (MAX_CHANGED_NAMES if label == "definitions" else MAX_SYMBOLS)
                lines.append("  %s: %s%s" % (label, ", ".join(items[:len(items) - max(more, 0)]),
                                             " (+%d more)" % more if more > 0 else ""))
    return lines


# `changed`: possible weakened guards, a section printed only when something is found. By path,
# and by counting marker lines in the two versions of each file (so a moved line counts for
# nothing): approximate, never a filter.
