"""Tests for codemap.py: python3 -m unittest discover -s <this folder>"""
import contextlib
import io
import os
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import codemap  # noqa: E402


def run(*argv):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        code = codemap.main(list(argv))
    return code, buf.getvalue()


class CodemapTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = self.tmp.name
        self.write("app/main.py", "from app import util\n\ndef run():\n    pass\n")
        self.write("app/util.py", "class Helper:\n    pass\n\ndef _private():\n    pass\n")
        self.write("web/index.ts", "import { x } from './lib';\nexport function start() {}\n")
        self.write("web/lib.ts", "export const x = 1;\n")
        self.write("tests/test_util.py", "def test_helper():\n    pass\n")
        subprocess.run(["git", "init", "-q", self.root], check=True)
        subprocess.run(["git", "-C", self.root, "add", "-A"], check=True)

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, rel, text, newline="\n"):
        path = os.path.join(self.root, *rel.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline=newline) as fh:
            fh.write(text)

    def read(self, rel):
        with open(os.path.join(self.root, *rel.split("/")), encoding="utf-8") as fh:
            return fh.read()

    def test_build_then_check_is_current(self):
        self.assertEqual(run("build", "--root", self.root)[0], 0)
        text = self.read("docs/code-map.md")
        self.assertIn("`app/util.py` — Helper", text)
        self.assertNotIn("_private", text)
        self.assertNotIn("test_helper", text)
        self.assertIn("`app/util.py` — imported by 1 files", text)
        self.assertIn("`web/lib.ts` — imported by 1 files", text)
        self.assertEqual(run("check", "--root", self.root)[0], 0)

    def test_build_is_deterministic(self):
        run("build", "--root", self.root)
        first = self.read("docs/code-map.md")
        run("build", "--root", self.root)
        self.assertEqual(first, self.read("docs/code-map.md"))

    def test_code_change_makes_it_stale(self):
        run("build", "--root", self.root)
        self.write("app/util.py", "class Helper:\n    pass\n\ndef new_api():\n    pass\n")
        self.assertEqual(run("check", "--root", self.root)[0], 1)

    def test_crlf_checkout_is_still_current(self):
        run("build", "--root", self.root)
        text = self.read("docs/code-map.md")
        self.write("docs/code-map.md", text, newline="\r\n")
        self.assertEqual(run("check", "--root", self.root)[0], 0)

    def test_missing_map_is_stale(self):
        self.assertEqual(run("check", "--root", self.root)[0], 1)

    def test_split_pages_and_stale_page_removal(self):
        old = codemap.SPLIT_ABOVE
        codemap.SPLIT_ABOVE = 2
        try:
            run("build", "--root", self.root)
            self.assertTrue(os.path.exists(os.path.join(self.root, "docs/code-map/app.md")))
            self.write("docs/code-map/gone.md", "# Code map\n\nGenerated by code-map (format 1)\n")
            self.assertEqual(run("check", "--root", self.root)[0], 1)
            run("build", "--root", self.root)
            self.assertFalse(os.path.exists(os.path.join(self.root, "docs/code-map/gone.md")))
            self.assertEqual(run("check", "--root", self.root)[0], 0)
            self.write("docs/code-map/app.md", "hand-written page\n")
            self.assertEqual(run("build", "--root", self.root)[0], 2)
            self.assertEqual(self.read("docs/code-map/app.md"), "hand-written page\n")
            self.write("README.md", "readme\n")
            self.assertEqual(run("build", "--root", self.root, "--out", "README.md")[0], 2)
            self.assertEqual(self.read("README.md"), "readme\n")
        finally:
            codemap.SPLIT_ABOVE = old

    def vault_setup(self):
        self.write("docs/vault/index.md", "- [[mimari]]\n- [[Ödeme]]\n- [[map]]\n")
        self.write("docs/vault/topics/mimari.md", "See `app/util.py` and [[yok]].\n"
                   "```\n[[inside-fence]]\n```\n")
        self.write("docs/vault/Ödeme.md", "Uses `web/lib.ts:x`.\n")
        self.write("docs/vault/orphan.md", "nothing links here\n")
        self.write(".env", "SECRET=1\n")
        self.write("app/secrets.py", "def leak():\n    pass\n")
        subprocess.run(["git", "-C", self.root, "add", "-A"], check=True)

    def test_vault_links_mentions_and_sensitive_files(self):
        self.vault_setup()
        run("build", "--root", self.root)
        text = self.read("docs/vault/map.md")
        self.assertIn("4 pages; 1 broken links; 1 orphan pages", text)
        self.assertIn("broken: `docs/vault/topics/mimari.md:1` → [[yok]]", text)
        self.assertNotIn("inside-fence", text)
        self.assertIn("orphan: `docs/vault/orphan.md`", text)
        self.assertNotIn("secrets.py", text)
        self.assertNotIn("leak", text)
        code, out = run("mentions", "app/util.py", "web/lib.ts", "--root", self.root)
        self.assertIn("docs/vault/topics/mimari.md:1 mentions app/util.py", out)
        self.assertIn("docs/vault/Ödeme.md:1 mentions web/lib.ts", out)
        self.assertEqual(run("check", "--root", self.root)[0], 0)
        self.write("docs/vault/index.md", "- [[mimari]]\n- [[Ödeme]]\n- [[map]]\n- [[orphan]]\n")
        self.assertEqual(run("check", "--root", self.root)[0], 1)

    def test_mentions_since_base(self):
        self.vault_setup()
        subprocess.run(["git", "-C", self.root, "-c", "user.name=t", "-c", "user.email=t@t",
                        "commit", "-qm", "base"], check=True)
        base = subprocess.run(["git", "-C", self.root, "rev-parse", "HEAD"],
                              capture_output=True, check=True).stdout.decode().strip()
        self.write("app/util.py", "class Helper:\n    pass\n\ndef added():\n    pass\n")
        code, out = run("mentions", "--base", base, "--root", self.root)
        self.assertIn("mimari.md:1 mentions app/util.py", out)
        self.assertNotIn("web/lib.ts", out)

    def test_config_written_and_respected(self):
        run("build", "--root", self.root)
        self.assertIn('"map": "docs/code-map.md"', self.read(".codemap.json"))
        self.write("docs/vault/a.md", "[[b]]\n")
        self.write("docs/vault/b.md", "[[a]]\n")
        subprocess.run(["git", "-C", self.root, "add", "-A"], check=True)
        self.assertIn("map: docs/code-map.md", run("detect", "--root", self.root)[1])
        run("build", "--root", self.root, "--redetect")
        self.assertIn("vault: docs/vault", run("detect", "--root", self.root)[1])
        self.assertIn("### Vault pages", self.read("docs/vault/map.md"))

    def test_detects_obsidian_vault_and_keeps_hand_written_map(self):
        self.write("knowledge/base/Home.md", "# Ana sayfa\n\n[[Notes]]\n")
        self.write("knowledge/base/Notes.md", "---\ntitle: Notlar\n---\nbody\n")
        self.write("knowledge/base/map.md", "my own map\n")
        os.makedirs(os.path.join(self.root, "knowledge", "base", ".obsidian"))
        subprocess.run(["git", "-C", self.root, "add", "-A"], check=True)
        out = run("detect", "--root", self.root)[1]
        self.assertIn("vault: knowledge/base (has .obsidian/)", out)
        self.assertIn("map: knowledge/base/code-map.md", out)
        run("build", "--root", self.root)
        self.assertEqual(self.read("knowledge/base/map.md"), "my own map\n")
        text = self.read("knowledge/base/code-map.md")
        self.assertIn("| `knowledge/base/Home.md` | Ana sayfa |", text)
        self.assertIn("| `knowledge/base/Notes.md` | Notlar |", text)
        self.assertEqual(run("check", "--root", self.root)[0], 0)

    def test_detects_wikilinked_folder(self):
        for i in range(6):
            self.write("brain/topics/p%d.md" % i, "[[p%d]]\n" % ((i + 1) % 6))
        subprocess.run(["git", "-C", self.root, "add", "-A"], check=True)
        self.assertIn("vault: brain/topics", run("detect", "--root", self.root)[1])

    def test_page_names_never_collide(self):
        names = codemap.page_names([".", "root", "_root", "a b", "a_b", "Docs", "docs", "con"])
        self.assertEqual(len({v.lower() for v in names.values()}), 8)
        self.assertEqual(names["con"], "_con.md")

    def test_large_directory_is_split_by_subdirectory(self):
        old = codemap.SPLIT_ABOVE
        codemap.SPLIT_ABOVE = 3
        try:
            for i in range(4):
                self.write("app/sub%d/m.py" % i, "def f%d():\n    pass\n" % i)
            subprocess.run(["git", "-C", self.root, "add", "-A"], check=True)
            run("build", "--root", self.root)
            pages = os.listdir(os.path.join(self.root, "docs", "code-map"))
            self.assertIn("app__sub0.md", pages)
            self.assertIn("app.md", pages)
        finally:
            codemap.SPLIT_ABOVE = old

    def test_python_symbols_do_not_depend_on_the_python_version(self):
        self.write("lib/gen.py", 'def generic[T](x: T) -> T:\n    return x\n\n'
                   'DOC = """\ndef not_a_def():\n"""\n\nfrom app import (\n    util,\n)\n')
        subprocess.run(["git", "-C", self.root, "add", "-A"], check=True)
        symbols, imports = codemap.python_info(self.read("lib/gen.py"))
        self.assertEqual([n for n, _ in symbols], ["generic"])
        self.assertIn((0, "app.util"), imports)

    def test_git_failure_inside_a_repo_is_an_error(self):
        os.environ["GIT_DIR"] = os.path.join(self.root, "missing")
        try:
            self.assertEqual(run("build", "--root", self.root)[0], 2)
        finally:
            del os.environ["GIT_DIR"]

    def git(self, *args):
        return subprocess.run(["git", "-C", self.root, "-c", "user.name=t", "-c", "user.email=t@t"]
                              + list(args), capture_output=True, check=True).stdout.decode().strip()

    def test_mentions_cover_deleted_renamed_and_dot_paths(self):
        self.write("app/old.py", "def gone():\n    pass\n")
        self.write(".github/ci.yml", "on: push\n")
        self.write("docs/vault/index.md", "- [[ops]]\n")
        self.write("docs/vault/ops.md", "`app/old.py`, `./.github/ci.yml`, `web/` and `app/util.py:3`\n")
        self.git("add", "-A")
        self.git("commit", "-qm", "base")
        base = self.git("rev-parse", "HEAD")
        self.git("rm", "-q", "app/old.py")
        self.git("mv", "app/util.py", "app/helpers.py")
        self.write(".github/ci.yml", "on: [push]\n")
        self.write("web/lib.ts", "export const y = 2;\n")
        out = run("mentions", "--base", base, "--root", self.root)[1]
        for path in ("app/old.py", ".github/ci.yml", "web/lib.ts", "app/util.py"):
            self.assertIn("mentions " + path, out)

    def test_symlinks_are_skipped_from_git_modes(self):
        if not hasattr(os, "symlink"):
            self.skipTest("no symlinks")
        os.symlink("util.py", os.path.join(self.root, "app", "alias.py"))
        self.git("add", "-A")
        run("build", "--root", self.root)
        self.assertNotIn("alias.py", self.read("docs/code-map.md"))

    def test_detection_never_reads_secret_folders(self):
        for i in range(5):
            self.write("secrets/x%d.md" % i, "[[x%d]]\n" % i)
        self.git("add", "-A")
        self.assertIn("vault: none", run("detect", "--root", self.root)[1])

    def test_vault_at_repository_root(self):
        os.makedirs(os.path.join(self.root, ".obsidian"))
        self.write("index.md", "[[topic]]\n")
        self.write("topics/topic.md", "# Konu\n")
